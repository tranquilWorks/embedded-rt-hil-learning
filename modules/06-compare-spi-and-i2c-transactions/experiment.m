%% P06 - Compare SPI and I2C Transactions
% Read: P05 made UART framing overhead and receiver timing visible. P06
% keeps one register-read request and payload fixed, then accounts for the
% clock cells and protocol responses used by SPI and I2C.
close all;

%% Baseline - the same four-byte register read at equal configured clocks
input = p06_scenario('baseline');
baseline = model(input.payload_bytes, input.spi_clock_hz, ...
    input.i2c_clock_hz, input.i2c_address_7bit, ...
    input.register_address, input.fault, ...
    input.transaction_timeout_us);
baselineRepeat = model(input.payload_bytes, input.spi_clock_hz, ...
    input.i2c_clock_hz, input.i2c_address_7bit, ...
    input.register_address, input.fault, ...
    input.transaction_timeout_us);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic transaction baseline changed between identical calls.');
assert(baseline.spi.command_byte == 173 && ...
    isequal(baseline.i2c.header_bytes, [144 45 145]), ...
    'The baseline must encode SPI 0xAD and I2C 0x90, 0x2D, 0x91.');
assert(baseline.spi.clocked_bit_count == 40 && ...
    baseline.i2c.nominal_clocked_bit_count == 63, ...
    'Four returned bytes require 40 SPI pulses and 63 I2C pulses.');
assert(isequal(baseline.i2c.response_bits, [0 0 0 0 0 0 1]) && ...
    baseline.i2c.intentional_final_nack && ...
    ~baseline.i2c.target_nack_detected, ...
    'The controller final-read NACK must terminate a successful I2C read.');
assert(baseline.spi.payload_correct && baseline.i2c.payload_correct, ...
    'Both clean baseline fixtures must return the expected payload.');

figure('Name', 'P06 baseline register-read clock cells');
subplot(2, 1, 1);
spiEdges = 0:baseline.spi.clocked_bit_count;
stairs(spiEdges, [baseline.spi.mosi_bits baseline.spi.mosi_bits(end)] + 1.5, ...
    'b-', 'LineWidth', 1.3);
hold on;
stairs(spiEdges, [baseline.spi.miso_actual_bits ...
    baseline.spi.miso_actual_bits(end)], 'k-', 'LineWidth', 1.3);
plot([baseline.spi.chip_select_assert_clock_index ...
    baseline.spi.chip_select_assert_clock_index ...
    baseline.spi.chip_select_deassert_clock_index ...
    baseline.spi.chip_select_deassert_clock_index], ...
    [4 3 3 4], 'g-', 'LineWidth', 1.3);
hold off;
grid on;
xlabel('SPI clock pulse index');
ylabel('Logic level plus lane offset');
ylim([-0.2 4.2]);
legend({'MOSI command/dummy (+1.5)', 'MISO dummy/payload', ...
    'Active-low CS (+3)'}, ...
    'Location', 'eastoutside');
title('Baseline view 1: MOSI and MISO shift simultaneously under one CS');

subplot(2, 1, 2);
i2cEdges = 0:baseline.i2c.actual_clocked_bit_count;
stairs(i2cEdges, [baseline.i2c.clocked_sda_bits ...
    baseline.i2c.clocked_sda_bits(end)], 'b-', 'LineWidth', 1.3);
hold on;
plot(baseline.i2c.response_clock_indices - 0.5, ...
    baseline.i2c.response_bits, 'ro', 'MarkerFaceColor', 'w', ...
    'LineWidth', 1.2);
plot([18 18], [-0.2 1.2], 'k:', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('I2C SCL clock pulse index');
ylabel('SDA logic level (0 or 1)');
ylim([-0.2 1.2]);
legend({'Clocked SDA cells', 'Ninth-clock responses', ...
    'Repeated START boundary'}, 'Location', 'eastoutside');
title('Baseline view 2: three headers, data, and owned ACK/NACK cells');

figure('Name', 'P06 baseline timing and efficiency metrics');
subplot(2, 1, 1);
bar([baseline.spi.modeled_elapsed_time_us ...
    baseline.i2c.modeled_elapsed_time_us]);
set(gca, 'XTickLabel', {'SPI', 'I2C'});
grid on;
ylabel('Nominal clocked time (us)');
title('Equal 400 kHz clocks isolate transaction-cell overhead');
subplot(2, 1, 2);
bar(100 .* [baseline.metrics.spi_nominal_payload_efficiency ...
    baseline.metrics.i2c_nominal_payload_efficiency]);
set(gca, 'XTickLabel', {'SPI', 'I2C'});
grid on;
ylabel('Read-payload efficiency (%)');
title('Useful payload bits divided by nominal clock pulses');

fprintf(['Baseline metrics: SPI %d pulses, %.1f us, %.1f%% efficiency; ' ...
    'I2C %d pulses, %.1f us, %.1f%% efficiency. START, repeated START, ' ...
    'and STOP are boundaries, not extra clock pulses.\n'], ...
    baseline.spi.clocked_bit_count, baseline.spi.clocked_time_us, ...
    100 .* baseline.metrics.spi_nominal_payload_efficiency, ...
    baseline.i2c.nominal_clocked_bit_count, ...
    baseline.i2c.clocked_time_us, ...
    100 .* baseline.metrics.i2c_nominal_payload_efficiency);

%% Sweep 1 - payload length amortizes fixed transaction headers
payloadCountSweep = [1 2 4 8 16];
spiPulseSweep = zeros(size(payloadCountSweep));
i2cPulseSweep = zeros(size(payloadCountSweep));
spiEfficiencySweep = zeros(size(payloadCountSweep));
i2cEfficiencySweep = zeros(size(payloadCountSweep));
spiTimeSweepUs = zeros(size(payloadCountSweep));
i2cTimeSweepUs = zeros(size(payloadCountSweep));
for sweepIndex = 1:numel(payloadCountSweep)
    sweptInput = p06_scenario('baseline', payloadCountSweep(sweepIndex));
    swept = model(sweptInput.payload_bytes, input.spi_clock_hz, ...
        input.i2c_clock_hz, input.i2c_address_7bit, ...
        input.register_address, sweptInput.fault, Inf);
    spiPulseSweep(sweepIndex) = swept.spi.clocked_bit_count;
    i2cPulseSweep(sweepIndex) = swept.i2c.nominal_clocked_bit_count;
    spiEfficiencySweep(sweepIndex) = ...
        swept.metrics.spi_nominal_payload_efficiency;
    i2cEfficiencySweep(sweepIndex) = ...
        swept.metrics.i2c_nominal_payload_efficiency;
    spiTimeSweepUs(sweepIndex) = swept.spi.clocked_time_us;
    i2cTimeSweepUs(sweepIndex) = swept.i2c.clocked_time_us;
    assert(swept.config.spi_clock_hz == baseline.config.spi_clock_hz && ...
        swept.config.i2c_clock_hz == baseline.config.i2c_clock_hz && ...
        swept.input.i2c_address_7bit == baseline.input.i2c_address_7bit && ...
        swept.input.register_address == baseline.input.register_address, ...
        'The payload-length lever must not change clocks or addressing.');
    assert(swept.i2c.intentional_final_nack && ...
        ~swept.i2c.target_nack_detected, ...
        'Every clean read must end with a controller-owned NACK.');
end
assert(isequal(spiPulseSweep, 8 .* (payloadCountSweep + 1)) && ...
    isequal(i2cPulseSweep, 9 .* (payloadCountSweep + 3)), ...
    'Payload sweep pulse counts must match independent protocol arithmetic.');
assert(all(diff(spiEfficiencySweep) > 0) && ...
    all(diff(i2cEfficiencySweep) > 0), ...
    'Both payload efficiencies must rise as fixed headers are amortized.');

figure('Name', 'P06 payload-length sweep');
subplot(2, 1, 1);
plot(payloadCountSweep, spiTimeSweepUs, 'o-', 'LineWidth', 1.3);
hold on;
plot(payloadCountSweep, i2cTimeSweepUs, 's-', 'LineWidth', 1.3);
hold off;
grid on;
xlabel('Returned payload length (bytes)');
ylabel('Nominal clocked time (us)');
legend({'SPI', 'I2C'}, 'Location', 'northwest');
title('Lever 1 changed view: more data adds protocol-specific pulse groups');
subplot(2, 1, 2);
plot(payloadCountSweep, 100 .* spiEfficiencySweep, ...
    'o-', 'LineWidth', 1.3);
hold on;
plot(payloadCountSweep, 100 .* i2cEfficiencySweep, ...
    's-', 'LineWidth', 1.3);
hold off;
grid on;
xlabel('Returned payload length (bytes)');
ylabel('Read-payload efficiency (%)');
legend({'SPI', 'I2C'}, 'Location', 'southeast');
title('Fixed command/address overhead matters less for longer reads');
fprintf(['Mechanism for sweep 1: C_SPI = 8(N+1), while ' ...
    'C_I2C = 9(N+3). MOSI and MISO share SPI pulses; every I2C byte ' ...
    'retains a ninth response pulse.\n']);

%% Sweep 2 - target clock stretch changes only modeled I2C elapsed time
stretchSweepUs = [0 25 100 250];
i2cElapsedSweepUs = zeros(size(stretchSweepUs));
i2cGoodputSweepBps = zeros(size(stretchSweepUs));
for sweepIndex = 1:numel(stretchSweepUs)
    if stretchSweepUs(sweepIndex) == 0
        sweptFault = struct('mode', 'none');
    else
        sweptFault = struct('mode', 'i2c-clock-stretch', ...
            'i2c_stretch_us', stretchSweepUs(sweepIndex));
    end
    swept = model(input.payload_bytes, input.spi_clock_hz, ...
        input.i2c_clock_hz, input.i2c_address_7bit, ...
        input.register_address, sweptFault, Inf);
    i2cElapsedSweepUs(sweepIndex) = ...
        swept.i2c.modeled_elapsed_time_us;
    i2cGoodputSweepBps(sweepIndex) = ...
        swept.metrics.i2c_correct_payload_goodput_bps;
    assert(isequal(swept.i2c.clocked_sda_bits, ...
        baseline.i2c.clocked_sda_bits) && ...
        swept.i2c.actual_clocked_bit_count == ...
        baseline.i2c.actual_clocked_bit_count, ...
        'Clock stretch must not add or mutate clocked I2C cells.');
    assert(isequaln(swept.spi, baseline.spi), ...
        'The I2C stretch lever must not mutate the SPI transaction.');
end
assert(all(abs(i2cElapsedSweepUs - ...
    (baseline.i2c.clocked_time_us + stretchSweepUs)) < 1e-12), ...
    'I2C elapsed time must equal clocked time plus modeled stretch.');
assert(all(diff(i2cGoodputSweepBps) < 0), ...
    'Longer stretch must lower completed-payload goodput.');

figure('Name', 'P06 I2C clock-stretch sweep');
subplot(2, 1, 1);
plot(stretchSweepUs, i2cElapsedSweepUs, 'o-', 'LineWidth', 1.3);
hold on;
plot(stretchSweepUs, repmat(baseline.spi.clocked_time_us, ...
    size(stretchSweepUs)), 'k--', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Modeled I2C clock stretch (us)');
ylabel('Modeled elapsed time (us)');
legend({'I2C', 'Unchanged SPI'}, 'Location', 'northwest');
title('Lever 2 changed view: an SCL-low interval adds elapsed time');
subplot(2, 1, 2);
plot(stretchSweepUs, i2cGoodputSweepBps, 's-', 'LineWidth', 1.3);
grid on;
xlabel('Modeled I2C clock stretch (us)');
ylabel('Correct payload goodput (bit/s)');
title('The byte sequence and pulse count stay fixed while goodput falls');
fprintf(['Mechanism for sweep 2: t_I2C = C_I2C/f_I2C + t_stretch. ' ...
    'The retained delay is synthetic and does not establish an electrical ' ...
    'or device timing limit.\n']);

%% Broken case - completion is not the same as verified payload acceptance
nackInput = p06_scenario('target-nack');
nack = model(nackInput.payload_bytes, nackInput.spi_clock_hz, ...
    nackInput.i2c_clock_hz, nackInput.i2c_address_7bit, ...
    nackInput.register_address, nackInput.fault, ...
    nackInput.transaction_timeout_us);
spiFaultInput = p06_scenario('spi-corruption');
spiFault = model(spiFaultInput.payload_bytes, ...
    spiFaultInput.spi_clock_hz, spiFaultInput.i2c_clock_hz, ...
    spiFaultInput.i2c_address_7bit, spiFaultInput.register_address, ...
    spiFaultInput.fault, spiFaultInput.transaction_timeout_us);
timeoutInput = p06_scenario('stretch-timeout');
timeoutCase = model(timeoutInput.payload_bytes, ...
    timeoutInput.spi_clock_hz, timeoutInput.i2c_clock_hz, ...
    timeoutInput.i2c_address_7bit, timeoutInput.register_address, ...
    timeoutInput.fault, timeoutInput.transaction_timeout_us);

assert(nack.i2c.target_nack_detected && ...
    nack.i2c.target_nack_index == 2 && ...
    nack.i2c.actual_clocked_bit_count == 18 && ...
    ~nack.i2c.repeated_start_present && ...
    isempty(nack.i2c.committed_payload_bytes), ...
    'A register-byte target NACK must stop before repeated START or data.');
assert(spiFault.spi.transaction_complete && ...
    ~spiFault.spi.payload_correct && ...
    ~spiFault.spi.error_detected && ...
    spiFault.spi.received_payload_bytes(2) == 87, ...
    'Generic SPI must not invent an ACK for one silently flipped data bit.');
assert(timeoutCase.spi.transaction_complete && ...
    timeoutCase.i2c.timed_out && ...
    ~timeoutCase.i2c.transaction_complete && ...
    isempty(timeoutCase.i2c.committed_payload_bytes), ...
    'The fixed deadline must accept SPI and reject the stretched I2C result.');
assert(baseline.i2c.intentional_final_nack && ...
    ~baseline.i2c.error_detected, ...
    'A controller final-read NACK is termination, not a target failure.');

recovered = model(input.payload_bytes, input.spi_clock_hz, ...
    input.i2c_clock_hz, input.i2c_address_7bit, ...
    input.register_address, [], []);
assert(isequaln(recovered, baseline), ...
    'Removing fault and deadline inputs must exactly recover the baseline.');

figure('Name', 'P06 broken transaction assumptions');
subplot(2, 1, 1);
plot(1:numel(baseline.i2c.response_bits), ...
    baseline.i2c.response_bits, 'bo-', 'LineWidth', 1.3);
hold on;
plot(1:numel(nack.i2c.response_bits), nack.i2c.response_bits, ...
    'rx--', 'LineWidth', 1.5, 'MarkerSize', 9);
hold off;
grid on;
xlabel('Ninth-clock response index');
ylabel('SDA response bit (0=ACK, 1=NACK)');
ylim([-0.2 1.2]);
legend({'Clean read: final controller NACK', ...
    'Broken read: target NACK'}, 'Location', 'northwest');
title('Response ownership determines whether a high ninth bit is failure');
subplot(2, 1, 2);
outcomeMatrix = [ ...
    nack.i2c.transaction_complete nack.i2c.payload_correct ...
        nack.i2c.error_detected; ...
    spiFault.spi.transaction_complete spiFault.spi.payload_correct ...
        spiFault.spi.error_detected; ...
    timeoutCase.i2c.transaction_complete timeoutCase.i2c.payload_correct ...
        timeoutCase.i2c.error_detected];
bar(double(outcomeMatrix));
set(gca, 'XTickLabel', {'I2C target NACK', 'SPI bit flip', ...
    'I2C deadline'});
grid on;
ylabel('Outcome indicator (0 or 1)');
legend({'Complete', 'Payload correct', 'Error observed'}, ...
    'Location', 'eastoutside');
title('NACK is visible, SPI corruption is not generically acknowledged');

fprintf(['Broken-case explanation: a target NACK aborts I2C before data; ' ...
    'the normal final controller NACK does not. SPI can finish every clock ' ...
    'while a returned bit is wrong because this fixture has no device-level ' ...
    'status or checksum. Resetting inputs proves state-free recovery.\n']);
