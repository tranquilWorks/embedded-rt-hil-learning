assertReject(@() model(1, 400000, 400000, 72, 45, {'none'}, Inf), ...
    'P06:model:Fault');
assertReject(@() model(1, 400000, 400000, 72, 45, struct(), Inf), ...
    'P06:model:Fault');
extraFault = struct('mode', 'none', 'extra', 1);
assertReject(@() model(1, 400000, 400000, 72, 45, extraFault, Inf), ...
    'P06:model:Fault');
badMode = struct('mode', 'spi-nack');
assertReject(@() model(1, 400000, 400000, 72, 45, badMode, Inf), ...
    'P06:model:FaultMode');
