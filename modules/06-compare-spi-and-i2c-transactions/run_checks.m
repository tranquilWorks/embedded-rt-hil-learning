assertReject(@() model(1, 400000, 400000, 72, 45, missingAck, Inf), ...
    'P06:model:FaultField');
badAck = struct('mode', 'i2c-target-nack', 'i2c_ack_index', 4);
assertReject(@() model(1, 400000, 400000, 72, 45, badAck, Inf), ...
    'P06:model:I2CAckIndex');
missingSpiBit = struct('mode', 'spi-bit-flip', ...
    'spi_payload_index', 1);
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    missingSpiBit, Inf), 'P06:model:FaultField');
badSpiPayload = struct('mode', 'spi-bit-flip', ...
    'spi_payload_index', 2, 'spi_bit_index', 0);
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    badSpiPayload, Inf), 'P06:model:SPIPayloadIndex');
badSpiBit = struct('mode', 'spi-bit-flip', ...
    'spi_payload_index', 1, 'spi_bit_index', 8);
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    badSpiBit, Inf), 'P06:model:SPIBitIndex');
missingStretch = struct('mode', 'i2c-clock-stretch');
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    missingStretch, Inf), 'P06:model:FaultField');
badStretch = struct('mode', 'i2c-clock-stretch', 'i2c_stretch_us', 0);
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    badStretch, Inf), 'P06:model:ClockStretch');
hugeStretch = struct('mode', 'i2c-clock-stretch', ...
    'i2c_stretch_us', 1e6 + 1);
assertReject(@() model(1, 400000, 400000, 72, 45, ...
    hugeStretch, Inf), 'P06:model:ClockStretch');

tooManyPayloadBytes = zeros(1, 100001);
assertReject(@() model(tooManyPayloadBytes, 400000, 400000, 72, 45), ...
    'P06:model:ResourceBound');
clear tooManyPayloadBytes;
