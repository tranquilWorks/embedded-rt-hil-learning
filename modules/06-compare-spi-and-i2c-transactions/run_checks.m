assertReject(@() model(tooManyClockedCells, 400000, 400000, 72, 45), ...
    'P06:model:ResourceBound');
clear tooManyClockedCells;
assertReject(@() p06_scenario({'baseline'}), 'P06:scenario:Kind');
assertReject(@() p06_scenario('baseline', -1), ...
    'P06:scenario:PayloadCount');
assertReject(@() p06_scenario('spi-corruption', 1), ...
    'P06:scenario:PayloadCount');
assertReject(@() p06_scenario('unknown'), 'P06:scenario:Kind');

afterRejection = model(fixture.payload_bytes, 400000, 400000, 72, 45);
assert(isequaln(afterRejection, clean), ...
    'A malformed call must not contaminate the next valid calculation.');

disp('P06 checks passed.');
end

function assertReject(callable, expectedIdentifier)
didReject = false;
receivedIdentifier = '<none>';
try
    callable();
catch caught
    receivedIdentifier = caught.identifier;
    didReject = strcmp(caught.identifier, expectedIdentifier);
end
assert(didReject, 'Expected rejection %s but received %s.', ...
    expectedIdentifier, receivedIdentifier);
end
