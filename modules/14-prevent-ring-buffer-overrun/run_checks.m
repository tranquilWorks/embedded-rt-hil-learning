    50, 200, 4, 200, 8, 'drop-newest', Inf, ...
    'continue-waiting'), 'P14:model:SourcePrecision');

assertReject(@() modelFcn(1, 0, 200, 4, 200, 8, ...
    'drop-newest', Inf, 'continue-waiting'), ...
    'P14:model:ProducerPeriod');
assertReject(@() modelFcn(1, 50, Inf, 4, 200, 8, ...
    'drop-newest', Inf, 'continue-waiting'), ...
