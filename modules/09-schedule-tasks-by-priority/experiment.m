%% P09 - Schedule Tasks by Priority
% Read: P08 stopped its command-latency model at the software scheduling
% boundary. P09 makes that missing CPU-sharing layer visible: every release
% creates a distinct job, and the highest-priority ready job owns one core.
close all;

%% Baseline - release, preempt, resume, and finish deterministic jobs
input = p09_scenario('baseline');
baseline = model(input.period_ms, input.execution_ms, ...
    input.relative_deadline_ms, input.priority, input.phase_ms, ...
    input.tick_ms, input.horizon_ms, input.deadline_action);
baselineRepeat = model(input.period_ms, input.execution_ms, ...
    input.relative_deadline_ms, input.priority, input.phase_ms, ...
    input.tick_ms, input.horizon_ms, input.deadline_action);
assert(isequaln(baseline, baselineRepeat), ...
    'The fixed-priority baseline must repeat exactly.');
expectedOwner = [ ...
    1 2 2 3 3 1 3 3 3 0 1 2 2 0 0 1 0 0 0 0 ...
    1 2 2 3 3 1 3 3 3 0 1 2 2 0 0 1 0 0 0 0];
assert(isequal(baseline.schedule.owner_task_id, expectedOwner), ...
    'The baseline owner sequence must retain its declared dispatch order.');
assert(isequal(baseline.metrics.release_count_by_task, [8 4 2]) && ...
    isequal(baseline.metrics.service_time_ms_by_task, [8 8 10]), ...
    'The baseline must retain every release and unit of executed work.');
assert(isequal(baseline.metrics.worst_response_ms_by_task, [1 3 9]) && ...
    isequal(baseline.metrics.deadline_miss_count_by_task, [0 0 0]) && ...
    baseline.metrics.preemption_count == 2, ...
    'Baseline response times, deadline outcomes, and preemptions changed.');
assert(abs(baseline.metrics.nominal_utilization - 0.65) < 1e-14 && ...
    abs(baseline.metrics.busy_fraction - 0.65) < 1e-14 && ...
    abs(baseline.metrics.idle_fraction - 0.35) < 1e-14, ...
    'Baseline demand, busy time, and idle time must balance.');

figure('Name', 'P09 baseline CPU ownership');
stairs(baseline.schedule.time_edges_ms, ...
    [baseline.schedule.owner_task_id ...
    baseline.schedule.owner_task_id(end)], 'LineWidth', 1.4);
grid on;
xlabel('Time (ms)');
ylabel('Processor owner (task ID)');
yticks(0:3);
yticklabels({'Idle', 'Control', 'Telemetry', 'Logger'});
ylim([-0.25 3.25]);
title('Baseline view 1: high-priority releases preempt and later resume logger jobs');

figure('Name', 'P09 baseline job response and deadlines');
jobDeadlineMs = baseline.input.relative_deadline_ms( ...
    baseline.jobs.task_id);
bar(baseline.jobs.id, baseline.jobs.response_ms, 0.72, ...
    'FaceColor', [0.25 0.55 0.85]);
hold on;
plot(baseline.jobs.id, jobDeadlineMs, 'k.', 'MarkerSize', 12);
hold off;
grid on;
xlabel('Released job ID (count)');
ylabel('Response time and relative deadline (ms)');
legend({'Completed response', 'Relative deadline'}, ...
    'Location', 'northwest');
title('Baseline view 2: every completed response remains at or below its deadline');

fprintf(['Baseline metrics: U=%.2f, busy %.1f ms, idle %.1f ms, ' ...
    'worst responses [%g %g %g] ms, misses [%d %d %d], ' ...
    'preemptions %d.\n'], baseline.metrics.nominal_utilization, ...
    baseline.metrics.busy_time_ms, baseline.metrics.idle_time_ms, ...
    baseline.metrics.worst_response_ms_by_task, ...
    baseline.metrics.deadline_miss_count_by_task, ...
    baseline.metrics.preemption_count);

%% Sweep 1 - change only the fixed-priority assignment
prioritySweep = [3 2 1; 2 3 1; 3 1 2];
priorityWorstResponseMs = zeros(size(prioritySweep));
priorityMissCount = zeros(size(prioritySweep));
for sweepIndex = 1:size(prioritySweep, 1)
    swept = model(input.period_ms, input.execution_ms, ...
        input.relative_deadline_ms, prioritySweep(sweepIndex, :), ...
        input.phase_ms, input.tick_ms, input.horizon_ms, ...
        input.deadline_action);
    priorityWorstResponseMs(sweepIndex, :) = ...
        swept.metrics.worst_response_ms_by_task;
    priorityMissCount(sweepIndex, :) = ...
        swept.metrics.deadline_miss_count_by_task;
    assert(isequal(swept.input.period_ms, baseline.input.period_ms) && ...
        isequal(swept.input.execution_ms, baseline.input.execution_ms) && ...
        isequal(swept.input.relative_deadline_ms, ...
        baseline.input.relative_deadline_ms) && ...
        isequal(swept.input.phase_ms, baseline.input.phase_ms) && ...
        isequal(swept.metrics.release_count_by_task, ...
        baseline.metrics.release_count_by_task) && ...
        swept.metrics.nominal_utilization == ...
        baseline.metrics.nominal_utilization, ...
        'Priority lever must not mutate timing, releases, or utilization.');
end
assert(isequal(priorityWorstResponseMs, [1 3 9; 3 2 9; 1 9 7]) && ...
    ~any(priorityMissCount(:)), ...
    'The safe priority-order sweep response contract changed.');

figure('Name', 'P09 priority assignment sweep');
plot(1:3, priorityWorstResponseMs(:, 1), 'o-', 'LineWidth', 1.4);
hold on;
plot(1:3, priorityWorstResponseMs(:, 2), 's-', 'LineWidth', 1.4);
plot(1:3, priorityWorstResponseMs(:, 3), '^-', 'LineWidth', 1.4);
hold off;
grid on;
xticks(1:3);
xticklabels({'C>T>L', 'T>C>L', 'C>L>T'});
xlabel('Fixed-priority assignment (larger number runs first)');
ylabel('Observed worst response time (ms)');
legend(input.task_names, 'Location', 'northwest');
title('Lever 1 changed view: priority moves interference between tasks');
fprintf(['Mechanism for sweep 1: changing only the priority order changes ' ...
    'who can delay whom; workload and release times stay fixed.\n']);

%% Sweep 2 - reset priority, then change only logger execution time
loggerExecutionSweepMs = [2 5 8];
loggerWorstResponseMs = zeros(size(loggerExecutionSweepMs));
utilizationSweep = zeros(size(loggerExecutionSweepMs));
missSweep = zeros(size(loggerExecutionSweepMs));
for sweepIndex = 1:numel(loggerExecutionSweepMs)
    sweptExecutionMs = input.execution_ms;
    sweptExecutionMs(3) = loggerExecutionSweepMs(sweepIndex);
    swept = model(input.period_ms, sweptExecutionMs, ...
        input.relative_deadline_ms, input.priority, input.phase_ms, ...
        input.tick_ms, input.horizon_ms, input.deadline_action);
    loggerWorstResponseMs(sweepIndex) = ...
        swept.metrics.worst_response_ms_by_task(3);
    utilizationSweep(sweepIndex) = swept.metrics.nominal_utilization;
    missSweep(sweepIndex) = sum( ...
        swept.metrics.deadline_miss_count_by_task);
    assert(isequal(swept.input.priority, baseline.input.priority) && ...
        isequal(swept.input.period_ms, baseline.input.period_ms) && ...
        isequal(swept.input.relative_deadline_ms, ...
        baseline.input.relative_deadline_ms) && ...
        isequal(swept.input.phase_ms, baseline.input.phase_ms) && ...
        isequal(swept.metrics.release_count_by_task, ...
        baseline.metrics.release_count_by_task), ...
        'Execution-time lever must not mutate priorities, releases, or deadlines.');
    assert(isequal(swept.metrics.worst_response_ms_by_task(1:2), [1 3]), ...
        'Lower-priority logger work must not delay higher-priority tasks.');
end
assert(max(abs(utilizationSweep - [0.50 0.65 0.80])) < 1e-14 && ...
    isequal(loggerWorstResponseMs, [5 9 15]) && ...
    ~any(missSweep), ...
    'The isolated logger execution-time sweep changed unexpectedly.');

figure('Name', 'P09 logger execution-time sweep');
yyaxis left;
plot(loggerExecutionSweepMs, loggerWorstResponseMs, 'o-', ...
    'LineWidth', 1.4);
ylabel('Logger worst response time (ms)');
yyaxis right;
plot(loggerExecutionSweepMs, 100 .* utilizationSweep, 's--', ...
    'LineWidth', 1.3);
ylabel('Nominal utilization (%)');
grid on;
xlabel('Logger execution time per job (ms)');
title('Lever 2 changed view: more low-priority work stretches its own completion');
fprintf(['Mechanism for sweep 2: resetting priority and adding only logger ' ...
    'work raises its response time without delaying ready higher-priority jobs.\n']);

%% Broken case - utilization below one does not rescue a bad priority map
brokenInput = p09_scenario('priority-misassigned');
broken = model(brokenInput.period_ms, brokenInput.execution_ms, ...
    brokenInput.relative_deadline_ms, brokenInput.priority, ...
    brokenInput.phase_ms, brokenInput.tick_ms, brokenInput.horizon_ms, ...
    brokenInput.deadline_action);
assert(broken.metrics.nominal_utilization == ...
    baseline.metrics.nominal_utilization && ...
    isequal(broken.metrics.release_count_by_task, ...
    baseline.metrics.release_count_by_task), ...
    'Broken priority mapping must retain workload and releases.');
assert(isequal(broken.metrics.worst_response_ms_by_task, [6 9 5]) && ...
    isequal(broken.metrics.deadline_miss_count_by_task, [2 0 0]), ...
    'Promoting logger must expose two control deadline misses.');

figure('Name', 'P09 deliberately broken priority assignment');
stairs(broken.schedule.time_edges_ms, ...
    [broken.schedule.owner_task_id broken.schedule.owner_task_id(end)], ...
    'LineWidth', 1.4);
grid on;
xlabel('Time (ms)');
ylabel('Processor owner (task ID)');
yticks(0:3);
yticklabels({'Idle', 'Control', 'Telemetry', 'Logger'});
ylim([-0.25 3.25]);
title(sprintf(['Broken assumption: U=%.2f, yet control misses %d deadlines ' ...
    'when logger has highest priority'], ...
    broken.metrics.nominal_utilization, ...
    broken.metrics.deadline_miss_count_by_task(1)));

recovered = model(input.period_ms, input.execution_ms, ...
    input.relative_deadline_ms, input.priority, input.phase_ms, ...
    input.tick_ms, input.horizon_ms, input.deadline_action);
assert(isequaln(recovered, baseline), ...
    'Resetting the priority map must recover the exact clean baseline.');

%% Deadline timeout, cancellation policy, and clean rollback
continuesLate = model(5, 6, 5, 1, 0, 1, 7, 'continue-late');
cancelsLate = model(5, 6, 5, 1, 0, 1, 7, ...
    'cancel-at-deadline');
assert(continuesLate.jobs.deadline_missed(1) && ...
    continuesLate.jobs.completion_ms(1) == 6 && ...
    ~continuesLate.jobs.cancelled_at_deadline(1), ...
    'Continue-late policy must record the timeout and finish the late job.');
assert(cancelsLate.jobs.deadline_missed(1) && ...
    cancelsLate.jobs.cancelled_at_deadline(1) && ...
    cancelsLate.jobs.service_ms(1) == 5 && ...
    cancelsLate.jobs.cancelled_work_ms(1) == 1, ...
    'Cancel-at-deadline must remove exactly the unfinished work at timeout.');
rolledBack = model(5, 6, 5, 1, 0, 1, 7, 'continue-late');
assert(isequaln(rolledBack, continuesLate), ...
    'Removing deadline cancellation must roll back to continue-late policy.');

disp(['Priority dispatch here is a bounded calculation, not proof of ' ...
    'MATLAB execution, an RTOS configuration, or processor timing.']);
