function responseMs = responseTimeRecurrence(periodMs, executionMs, priority)
% Independent recurrence for the declared independent preemptive task set.
taskCount = numel(periodMs);
responseMs = zeros(1, taskCount);
for taskId = 1:taskCount
    candidate = executionMs(taskId);
    for boundedIteration = 1:100
        higher = priority > priority(taskId);
        nextCandidate = executionMs(taskId) + sum( ...
            ceil(candidate ./ periodMs(higher)) .* executionMs(higher));
        if nextCandidate == candidate
            break;
        end
        candidate = nextCandidate;
    end
    responseMs(taskId) = candidate;
end
end

function assertReject(callable, expectedIdentifier)
didReject = false;
receivedIdentifier = '<none>';
try
    callable();
catch caught
    receivedIdentifier = caught.identifier;
    didReject = strcmp(caught.identifier, expectedIdentifier);
end
assert(didReject, 'Expected rejection %s but received %s.', ...
    expectedIdentifier, receivedIdentifier);
end
