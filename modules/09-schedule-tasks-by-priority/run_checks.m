function run_checks
%RUN_CHECKS Verify P09 scheduler semantics, boundaries, and recovery.

modelFcn = @model;
scenarioFcn = @p09_scenario;
fixture = scenarioFcn('baseline');
clean = modelFcn(fixture.period_ms, fixture.execution_ms, ...
    fixture.relative_deadline_ms, fixture.priority, fixture.phase_ms, ...
    fixture.tick_ms, fixture.horizon_ms, fixture.deadline_action);

%% Deterministic baseline, exact timeline, and conservation
repeat = modelFcn(fixture.period_ms, fixture.execution_ms, ...
    fixture.relative_deadline_ms, fixture.priority, fixture.phase_ms, ...
    fixture.tick_ms, fixture.horizon_ms, fixture.deadline_action);
assert(isequaln(clean, repeat), ...
    'Repeated baseline calls must be deterministic and state-isolated.');
expectedOwner = [ ...
    1 2 2 3 3 1 3 3 3 0 1 2 2 0 0 1 0 0 0 0 ...
    1 2 2 3 3 1 3 3 3 0 1 2 2 0 0 1 0 0 0 0];
assert(isequal(clean.schedule.owner_task_id, expectedOwner), ...
    'Baseline owner intervals must retain the exact dispatch sequence.');
assert(isequal(clean.metrics.release_count_by_task, [8 4 2]), ...
    'The half-open 40 ms horizon must release [8 4 2] jobs.');
assert(isequal(clean.metrics.completion_count_by_task, [8 4 2]), ...
    'Every baseline job must complete within the observation.');
assert(isequal(clean.metrics.service_time_ms_by_task, [8 8 10]), ...
    'Baseline service must retain [8 8 10] ms by task.');
assert(isequal(clean.metrics.worst_response_ms_by_task, [1 3 9]), ...
    'Baseline worst responses must be [1 3 9] ms.');
assert(isequal(clean.metrics.deadline_miss_count_by_task, [0 0 0]), ...
    'The baseline must have no deadline timeouts.');
assert(clean.metrics.preemption_count == 2 && ...
    sum(clean.jobs.preemption_count(clean.jobs.task_id == 3)) == 2, ...
    'The logger must be preempted by control exactly twice.');
assert(abs(clean.metrics.nominal_utilization - 0.65) < 1e-14, ...
    'Nominal utilization must equal 1/5 + 2/10 + 5/20.');
assert(clean.metrics.busy_time_ms == 26 && ...
    clean.metrics.idle_time_ms == 14 && ...
    clean.metrics.busy_time_ms + clean.metrics.idle_time_ms == 40, ...
    'Busy and idle time must conserve the 40 ms horizon.');
assert(abs(clean.metrics.busy_fraction - 0.65) < 1e-14 && ...
    abs(clean.metrics.idle_fraction - 0.35) < 1e-14, ...
    'Busy and idle fractions must match retained service.');
assert(clean.metrics.demand_conservation_error_ms == 0 && ...
    clean.metrics.released_demand_ms == ...
    clean.metrics.served_work_ms, ...
    'Released, served, remaining, and canceled demand must conserve work.');
assert(isequal(clean.metrics.release_count_by_task, ...
    clean.metrics.completion_count_by_task + ...
    clean.metrics.unfinished_count_by_task + ...
    clean.metrics.deadline_cancel_count_by_task), ...
    'Every released baseline job must have one terminal or pending state.');
assert(clean.metrics.max_ready_jobs >= 1 && ...
    clean.metrics.max_ready_jobs <= sum(clean.metrics.release_count_by_task), ...
    'Ready depth must remain within the bounded released-job population.');
assert(all(ismember(unique(clean.schedule.owner_task_id), 0:3)), ...
    'Every owner interval must be idle or one declared task.');
busyMask = clean.schedule.owner_task_id > 0;
assert(all(clean.schedule.selected_priority(busyMask) == ...
    clean.input.priority(clean.schedule.owner_task_id(busyMask))), ...
    'Selected priority must belong to the recorded CPU owner.');

%% Independent fixed-priority response calculation
independentResponseMs = responseTimeRecurrence( ...
    fixture.period_ms, fixture.execution_ms, fixture.priority);
assert(isequal(independentResponseMs, [1 3 9]), ...
    ['Independent higher-priority interference recurrence must produce ' ...
    '[1 3 9] ms.']);
assert(isequal(independentResponseMs, ...
    clean.metrics.worst_response_ms_by_task), ...
    'Observed synchronous baseline responses must match the recurrence.');

%% Release, preemption, resume, completion, and deterministic ties
loggerFirstJob = find(clean.jobs.task_id == 3 & ...
    clean.jobs.sequence == 1, 1);
assert(clean.jobs.start_ms(loggerFirstJob) == 3 && ...
    clean.jobs.completion_ms(loggerFirstJob) == 9 && ...
    clean.jobs.response_ms(loggerFirstJob) == 9, ...
    'The first logger job must run, be preempted, resume, and finish at 9 ms.');
assert(clean.schedule.owner_task_id(6) == 1 && ...
    clean.schedule.owner_task_id(7) == 3, ...
    'Control must preempt logger at 5 ms and logger must resume at 6 ms.');
equalPriority = modelFcn([10 10], [2 1], [10 10], [1 1], ...
    [0 0], 1, 3);
assert(isequal(equalPriority.schedule.owner_task_id, [1 1 2]), ...
    ['Equal-priority simultaneous jobs must use task ID, and the older ' ...
    'job must remain FIFO without time slicing.']);
assert(isequal(equalPriority.jobs.response_ms, [2 3]), ...
    'Equal-priority tie-breaking must retain exact response times.');

%% Zero-work, phase, horizon, and exact-deadline limiting cases
zeroWork = modelFcn(5, 0, 5, 1, 0, 1, 10);
assert(isequal(zeroWork.metrics.release_count_by_task, 2) && ...
    isequal(zeroWork.metrics.completion_count_by_task, 2) && ...
    all(zeroWork.jobs.response_ms == 0), ...
    'A zero-WCET job must complete exactly at each release.');
assert(all(zeroWork.schedule.owner_task_id == 0) && ...
    zeroWork.metrics.busy_time_ms == 0 && ...
    zeroWork.metrics.idle_time_ms == 10, ...
    'Zero-WCET releases must not consume a CPU interval.');
atHorizonPhase = modelFcn(5, 1, 5, 1, 10, 1, 10);
assert(isempty(atHorizonPhase.jobs.id) && ...
    atHorizonPhase.metrics.release_count_by_task == 0, ...
    'A phase exactly at the half-open horizon must not release a job.');
exactDeadline = modelFcn(5, 5, 5, 1, 0, 1, 5);
assert(exactDeadline.jobs.completion_ms(1) == 5 && ...
    ~exactDeadline.jobs.deadline_missed(1), ...
    'Completion exactly at the final deadline boundary must be on time.');

%% Timeout, continue-late, cancellation, and beyond-horizon classification
continuesLate = modelFcn(5, 6, 5, 1, 0, 1, 7, 'continue-late');
assert(continuesLate.jobs.deadline_missed(1) && ...
    continuesLate.jobs.miss_time_ms(1) == 5 && ...
    continuesLate.jobs.completion_ms(1) == 6, ...
    'One remaining tick at 5 ms must time out once and complete late at 6 ms.');
assert(~continuesLate.jobs.cancelled_at_deadline(1) && ...
    continuesLate.jobs.service_ms(1) == 6, ...
    'Continue-late policy must serve, not cancel, the expired remainder.');
assert(~continuesLate.jobs.deadline_missed(2) && ...
    continuesLate.jobs.unfinished_at_horizon(2) && ...
    continuesLate.jobs.absolute_deadline_ms(2) == 10, ...
    'A deadline beyond the horizon must remain unobserved, not missed.');
cancelsLate = modelFcn(5, 6, 5, 1, 0, 1, 7, ...
    'cancel-at-deadline');
assert(cancelsLate.jobs.deadline_missed(1) && ...
    cancelsLate.jobs.cancelled_at_deadline(1) && ...
    cancelsLate.jobs.cancellation_time_ms(1) == 5, ...
    'Cancel-at-deadline must remove the expired job before dispatch at 5 ms.');
assert(cancelsLate.jobs.service_ms(1) == 5 && ...
    cancelsLate.jobs.cancelled_work_ms(1) == 1 && ...
    isnan(cancelsLate.jobs.completion_ms(1)), ...
    'Deadline cancellation must retain five served and one canceled tick.');
assert(cancelsLate.schedule.owner_job_id(6) == 2 && ...
    ~cancelsLate.jobs.deadline_missed(2), ...
    'The replacement job must dispatch after cancellation without an invented miss.');
assert(cancelsLate.metrics.released_demand_ms == ...
    cancelsLate.metrics.served_work_ms + ...
    cancelsLate.metrics.cancelled_work_ms + ...
    cancelsLate.metrics.remaining_work_ms, ...
    'Cancellation must preserve released-demand accounting.');
explicitContinue = modelFcn(5, 6, 5, 1, 0, 1, 7, ...
    'continue-late');
defaultContinue = modelFcn(5, 6, 5, 1, 0, 1, 7, []);
assert(isequaln(explicitContinue, defaultContinue), ...
    'Empty deadline action must be compatible with continue-late default.');

%% Overlapping releases remain separate FIFO jobs
backlog = modelFcn(2, 3, 2, 1, 0, 1, 7, 'continue-late');
assert(isequal(backlog.jobs.id, 1:4) && ...
    isequal(backlog.jobs.release_ms, [0 2 4 6]) && ...
    isequal(backlog.jobs.absolute_deadline_ms, [2 4 6 8]), ...
    'Overlapping releases must retain four distinct jobs and deadlines.');
