fprintf(['Baseline metrics: writer lock [%.1f, %.1f) ms; reader wait ' ...
    '%.1f ms = commit %.1f + scope excess %.1f ms; response %.1f ms; ' ...
    'snapshot generation %.0f, coherent=%d.\n'], ...
