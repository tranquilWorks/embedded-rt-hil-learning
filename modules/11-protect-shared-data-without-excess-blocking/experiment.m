%% Wait timeout, reader cancellation, ownership, and recovery
exactTimeoutInput = input;
exactTimeoutInput.wait_timeout_ms = 1;
exactTimeoutInput.timeout_action = 'cancel-reader';
exactHandoff = runFixture(exactTimeoutInput);
assert(~exactHandoff.reader.wait_timed_out && ...
    ~exactHandoff.reader.cancelled_while_waiting && ...
    exactHandoff.reader.mutex_acquire_ms == 4 && ...
    exactHandoff.reader.snapshot_consistent, ...
    'Writer unlock at the one-millisecond timeout boundary must win.');

continueInput = p11_scenario('timeout-continue');
continued = runFixture(continueInput);
assert(continued.reader.wait_timed_out && ...
    continued.reader.wait_timeout_time_ms == 4 && ...
    ~continued.reader.cancelled_while_waiting && ...
    continued.reader.blocked_time_ms == 3 && ...
    continued.reader.completion_ms == 12 && ...
    continued.reader.snapshot_consistent, ...
    'Continue-waiting must record one timeout and preserve a coherent read.');

cancelInput = p11_scenario('timeout-cancel');
cancelled = runFixture(cancelInput);
assert(cancelled.reader.wait_timed_out && ...
    cancelled.reader.cancellation_time_ms == 4 && ...
    cancelled.reader.cancelled_work_ms == 6 && ...
    isnan(cancelled.reader.completion_ms) && ...
    cancelled.writer.mutex_release_ms == 6 && ...
    cancelled.writer.completed, ...
    'Reader cancellation must not unlock or cancel the writer.');
assert(cancelled.metrics.released_demand_ms == 12 && ...
    cancelled.metrics.served_work_ms == 6 && ...
    cancelled.metrics.cancelled_work_ms == 6 && ...
    cancelled.metrics.remaining_work_ms == 0 && ...
    cancelled.metrics.work_conservation_error_ms == 0, ...
    'Cancellation must conserve writer service and canceled reader work.');
rollback = runFixture(input);
assert(isequaln(rollback, baseline), ...
    'A clean call after cancellation must recover exact baseline state.');

disp(['Reader cancellation removes only modeled pending reader work; it ' ...
    'does not unlock the writer, repair data, or delete an RTOS task.']);
disp(['P11 outputs are synthetic calculations, not proof of MATLAB ' ...
    'execution, an RTOS/memory protocol, processor timing, or hardware behavior.']);
