%% Sweep 1 - change only private preparation and compare lock scopes
writerPrepareSweepMs = [2 3 4 5];
shortWaitMs = zeros(size(writerPrepareSweepMs));
shortResponseMs = zeros(size(writerPrepareSweepMs));
shortObservedVersion = zeros(size(writerPrepareSweepMs));
coarseWaitMs = zeros(size(writerPrepareSweepMs));
coarseResponseMs = zeros(size(writerPrepareSweepMs));
coarseExcessMs = zeros(size(writerPrepareSweepMs));
for sweepIndex = 1:numel(writerPrepareSweepMs)
    shortInput = p11_scenario('baseline', ...
        writerPrepareSweepMs(sweepIndex), 2, 1, 2, 16);
    coarseInput = p11_scenario('coarse-lock', ...
        writerPrepareSweepMs(sweepIndex), 2, 1, 2, 16);
    shortOut = runFixture(shortInput);
    coarseOut = runFixture(coarseInput);
    shortWaitMs(sweepIndex) = shortOut.reader.blocked_time_ms;
    shortResponseMs(sweepIndex) = shortOut.reader.response_ms;
    shortObservedVersion(sweepIndex) = ...
        shortOut.reader.observed_version;
    coarseWaitMs(sweepIndex) = coarseOut.reader.blocked_time_ms;
    coarseResponseMs(sweepIndex) = coarseOut.reader.response_ms;
    coarseExcessMs(sweepIndex) = ...
        coarseOut.reader.scope_excess_blocking_ms;
    assert(isequal(shortOut.input, coarseOut.input), ...
        'Lock-scope comparison must retain every numeric model input.');
    assert(shortOut.reader.snapshot_consistent && ...
        coarseOut.reader.snapshot_consistent && ...
        shortOut.reader.observed_version == 0 && ...
        coarseOut.reader.observed_version == 1, ...
        ['Both scopes must preserve coherence while exposing the ' ...
        'freshness-versus-wait tradeoff.']);
end
assert(isequal(shortWaitMs, [0 0 0 0]) && ...
    isequal(shortResponseMs, [4 4 4 4]) && ...
    isequal(shortObservedVersion, [0 0 0 0]), ...
    'Private preparation must not extend the short mutex.');
assert(isequal(coarseWaitMs, [3 4 5 6]) && ...
    isequal(coarseResponseMs, [7 8 9 10]) && ...
    isequal(coarseExcessMs, [1 2 3 4]), ...
    'Coarse-scope preparation wait references changed.');

figure('Name', 'P11 private preparation sweep');
plot(writerPrepareSweepMs, shortResponseMs, 'o-', ...
    'LineWidth', 1.4);
hold on;
plot(writerPrepareSweepMs, coarseResponseMs, 's-', ...
    'LineWidth', 1.4);
plot(writerPrepareSweepMs, coarseExcessMs, '^--', ...
    'LineWidth', 1.3);
hold off;
grid on;
xlabel('Writer private preparation (ms)');
ylabel('Reader response or excess wait (ms)');
legend({'Response: short mutex', 'Response: coarse mutex', ...
    'Scope-excess wait: coarse mutex'}, 'Location', 'northwest');
title('Lever 1 changed view: unrelated preparation must stay outside the mutex');
fprintf(['Mechanism for sweep 1: the short reader returns the previous ' ...
    'complete generation without waiting; coarse scope waits for work ' ...
    'that does not touch shared memory. Freshness is a separate contract.\n']);

%% Sweep 2 - reset preparation, then change protected record size
recordWordsSweep = [2 3 4 5];
wordWaitMs = zeros(size(recordWordsSweep));
wordResponseMs = zeros(size(recordWordsSweep));
wordCommitBlockingMs = zeros(size(recordWordsSweep));
for sweepIndex = 1:numel(recordWordsSweep)
    sweptInput = p11_scenario('baseline', 2, ...
        recordWordsSweep(sweepIndex), 3, 2, 16);
    swept = runFixture(sweptInput);
    wordWaitMs(sweepIndex) = swept.reader.blocked_time_ms;
    wordResponseMs(sweepIndex) = swept.reader.response_ms;
    wordCommitBlockingMs(sweepIndex) = ...
        swept.reader.commit_blocking_ms;
    assert(swept.input.writer_prepare_ms == 2 && ...
        swept.input.reader_release_ms == 3 && ...
        swept.input.reader_process_ms == 2 && ...
        swept.input.tick_ms == 1 && ...
        swept.input.horizon_ms == 16 && ...
        strcmp(swept.policy.protection, 'short-mutex'), ...
        'Record-size sweep must isolate its one protected-work input.');
    assert(swept.reader.snapshot_consistent && ...
        swept.reader.observed_version == 1 && ...
        swept.reader.scope_excess_blocking_ms == 0, ...
        'Protected record-size sweep must retain coherence and zero scope excess.');
end
assert(isequal(wordWaitMs, [1 2 3 4]) && ...
    isequal(wordCommitBlockingMs, [1 2 3 4]) && ...
    isequal(wordResponseMs, [5 7 9 11]), ...
    'Protected record-size sweep references changed.');

figure('Name', 'P11 protected record-size sweep');
plot(recordWordsSweep, wordWaitMs, 'o-', 'LineWidth', 1.4);
hold on;
plot(recordWordsSweep, wordResponseMs, 's-', 'LineWidth', 1.4);
hold off;
grid on;
xlabel('Protected record size (words)');
ylabel('Reader wait or response (ms)');
legend({'Commit blocking', 'Reader response'}, ...
    'Location', 'northwest');
title('Lever 2 changed view: necessary mutex work still sets a blocking bound');
fprintf(['Mechanism for sweep 2: after reset, each additional protected ' ...
    'word adds one writer commit tick and one reader copy tick. Priority ' ...
    'inheritance cannot make either operation disappear.\n']);

%% Broken case - the reader ignores the shared protection protocol
brokenInput = p11_scenario('unprotected-torn');
broken = runFixture(brokenInput);
expectedBrokenOwner = [1 1 1 2 2 2 2 1 0 0 0 0 0 0 0 0];
assert(isequal(broken.timeline.cpu_owner_task_id, ...
    expectedBrokenOwner) && ...
    broken.reader.blocked_time_ms == 0 && ...
    broken.reader.response_ms == 4, ...
    'Unprotected reader timing reference changed.');
assert(isequal(broken.reader.observed_values, [101 2]) && ...
    isequal(broken.reader.observed_version_by_word, [1 0]) && ...
    ~broken.reader.snapshot_consistent && ...
    broken.reader.torn_read_detected && ...
    broken.metrics.torn_read_count == 1, ...
    'The broken case must expose one deterministic mixed-generation snapshot.');
assert(isequal(broken.input, baseline.input) && ...
    broken.metrics.released_demand_ms == ...
    baseline.metrics.released_demand_ms && ...
    broken.metrics.served_work_ms == ...
    baseline.metrics.served_work_ms && ...
    isequal(broken.record.final_values, ...
    baseline.record.final_values), ...
    'Broken protection must retain numeric input, work, and final writer result.');

