title('Baseline view 1: the reader blocks while the writer completes commit');
subplot(2, 1, 2);
stairs(baseline.timeline.time_edges_ms, ...
    [baseline.timeline.mutex_owner_task_id ...
    baseline.timeline.mutex_owner_task_id(end)], 'LineWidth', 1.4);
grid on;
xlabel('Time (ms)');
ylabel('Mutex owner (task ID)');
yticks(0:2);
yticklabels({'Free', 'Writer', 'Reader'});
ylim([-0.25 2.25]);
title('CPU ownership and mutex ownership remain distinct');

figure('Name', 'P11 baseline record and snapshot progress');
subplot(2, 1, 1);
stairs(baseline.timeline.time_edges_ms, ...
    baseline.timeline.writer_committed_word_count, ...
    'LineWidth', 1.4);
hold on;
stairs(baseline.timeline.time_edges_ms, ...
