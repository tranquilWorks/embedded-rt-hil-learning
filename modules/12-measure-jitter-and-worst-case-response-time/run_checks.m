assert(single.metrics.reference_release_jitter_pp_ms == 0 && ...
    single.metrics.reference_response_jitter_pp_ms == 0 && ...
    single.metrics.fixture_observed_worst_response_ms == 6, ...
    'One retained job must have zero p-p jitter and a six-ms response.');
assert(isempty(single.reference.completion_interval_deviation_ms) && ...
    isempty(single.measurement.completion_interval_deviation_ms), ...
    'One job has no completion interval to compare.');

zeroResponse = modelFcn(20, 2, [0 0], 0, 0, 0, 1, 1, ...
    Inf, 'continue-observing');
assert(isequal(zeroResponse.reference.response_ms, [0 0]) && ...
    zeroResponse.metrics.fixture_observed_worst_response_ms == 0 && ...
    zeroResponse.metrics.reference_response_jitter_pp_ms == 0 && ...
    zeroResponse.metrics.reference_deadline_miss_count == 0, ...
    'Zero work must produce zero response and no miss.');

constantLate = modelFcn(20, 3, [0 0 0], 9, 0, 0, 8, 1, ...
    Inf, 'continue-observing');
assert(constantLate.metrics.reference_response_jitter_pp_ms == 0 && ...
    constantLate.metrics.reference_deadline_miss_count == 3, ...
    'Zero response jitter does not imply deadline safety.');

integerColumn = modelFcn(uint16(20), uint8(8), ...
    int8([0 1 -1 0 1 -1 0 1])', uint8(2), ...
    uint8([0 1 0 1 0 1 0 1])', ...
    uint8([0 0 1 0 2 0 1 3])', uint8(7), uint8(1), ...
    [], string('continue-observing'));
assert(isequaln(integerColumn, clean), ...
    ['Integer-class scalars and columns plus a scalar string must ' ...
    'normalize exactly.']);

emptyDefaults = modelFcn(fixture.period_ms, fixture.job_count, ...
    fixture.release_offset_ms, fixture.execution_ms, ...
    fixture.blocking_ms, fixture.interference_ms, ...
    fixture.deadline_ms, fixture.timestamp_tick_ms, [], []);
assert(isequaln(emptyDefaults, clean), ...
    'Empty timeout and action defaults must recover the baseline policy.');

scalarExpansion = modelFcn(20, 3, 0, 2, 1, 0, 4, 1, ...
    Inf, 'continue-observing');
assert(isequal(scalarExpansion.input.release_offset_ms, [0 0 0]) && ...
    isequal(scalarExpansion.input.execution_ms, [2 2 2]) && ...
    isequal(scalarExpansion.input.blocking_ms, [1 1 1]) && ...
    isequal(scalarExpansion.reference.response_ms, [3 3 3]), ...
    'Scalar component inputs must expand once per job.');

%% Callback-bound dependencies survive public path cleanup
callbackModel = modelFcn;
callbackScenario = scenarioFcn;
moduleFolder = fileparts(mfilename('fullpath'));
modulesFolder = fileparts(moduleFolder);
