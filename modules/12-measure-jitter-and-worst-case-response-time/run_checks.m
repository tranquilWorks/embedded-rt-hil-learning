callbackOut = callbackModel(callbackInput.period_ms, ...
    callbackInput.job_count, callbackInput.release_offset_ms, ...
    callbackInput.execution_ms, callbackInput.blocking_ms, ...
    callbackInput.interference_ms, callbackInput.deadline_ms, ...
    callbackInput.timestamp_tick_ms, ...
    callbackInput.response_timeout_ms, callbackInput.timeout_action);
assert(isequaln(callbackOut, clean), ...
    ['Callback-bound P12 dependencies must survive module path cleanup ' ...
    'plus a generic-model clear and conflicting P01 model path.']);
clear searchPathCleanup;

