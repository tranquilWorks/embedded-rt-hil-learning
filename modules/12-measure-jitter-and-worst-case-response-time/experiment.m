%% P12 - Measure Jitter and Worst-Case Response Time
% Read: P11 produced bounded blocking B. P12 places that value beside
% interference I and execution C, then measures distinct timestamp deltas:
% release offset j=a-n, response R=f-a, and nominal latency L=f-n=j+R.
close all;
runFixture = @(fixture) model(fixture.period_ms, fixture.job_count, ...
    fixture.release_offset_ms, fixture.execution_ms, ...
    fixture.blocking_ms, fixture.interference_ms, ...
    fixture.deadline_ms, fixture.timestamp_tick_ms, ...
    fixture.response_timeout_ms, fixture.timeout_action);

%% Baseline - read nominal, actual, start, and completion timestamps
input = p12_scenario('baseline');
baseline = runFixture(input);
baselineRepeat = runFixture(input);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic baseline must repeat exactly.');
assert(isequal(baseline.timeline.nominal_release_ms, ...
    [0 20 40 60 80 100 120 140]) && ...
    isequal(baseline.timeline.actual_release_ms, ...
    [0 21 39 60 81 99 120 141]) && ...
    isequal(baseline.timeline.start_ms, ...
    [0 22 40 61 83 100 121 145]) && ...
    isequal(baseline.timeline.completion_ms, ...
    [2 24 42 63 85 102 123 147]), ...
    'Baseline timestamp references changed.');
assert(isequal(baseline.reference.release_offset_ms, ...
    [0 1 -1 0 1 -1 0 1]) && ...
    isequal(baseline.reference.response_ms, ...
    [2 3 3 3 4 3 3 6]) && ...
    isequal(baseline.reference.nominal_completion_latency_ms, ...
    [2 4 2 3 5 2 3 7]), ...
    'Baseline release, response, or nominal-latency vectors changed.');
assert(baseline.metrics.reference_release_jitter_pp_ms == 2 && ...
    baseline.metrics.reference_response_jitter_pp_ms == 4 && ...
    baseline.metrics.fixture_observed_worst_response_ms == 6 && ...
    baseline.metrics.component_response_envelope_ms == 6 && ...
    baseline.metrics.reference_deadline_miss_count == 0, ...
    'Baseline jitter, worst response, envelope, or deadline result changed.');
assert(all(baseline.reference.end_to_end_identity_error_ms == 0) && ...
    all(baseline.reference.component_identity_error_ms == 0) && ...
    all(baseline.reference.completion_identity_error_ms == 0), ...
    'Baseline timestamp identities must close exactly.');

figure('Name', 'P12 baseline release timing');
stem(baseline.timeline.job_id, ...
    baseline.reference.release_offset_ms, 'filled', ...
    'LineWidth', 1.3);
grid on;
xlabel('Job (index)');
ylabel('Actual - nominal release (ms)');
title('Baseline view 1: release offset is signed around the nominal grid');

figure('Name', 'P12 baseline response decomposition');
bar(baseline.timeline.job_id, ...
    [baseline.input.blocking_ms(:) ...
    baseline.input.interference_ms(:) ...
    baseline.input.execution_ms(:)], 'stacked');
hold on;
plot(baseline.timeline.job_id, ...
    baseline.deadline.deadline_ms .* ...
    ones(size(baseline.timeline.job_id)), 'k--', 'LineWidth', 1.4);
hold off;
grid on;
xlabel('Job (index)');
ylabel('Response-time component (ms)');
legend({'Blocking B', 'Interference I', 'Execution C', ...
    'Deadline D'}, 'Location', 'northwest');
title('Baseline view 2: R = B + I + C; equality at D passes');

fprintf(['Baseline metrics: release jitter p-p %.1f ms; response jitter ' ...
    'p-p %.1f ms; finite-fixture observed worst response %.1f ms; ' ...
    'component envelope %.1f ms; deadline misses %.0f.\n'], ...
    baseline.metrics.reference_release_jitter_pp_ms, ...
    baseline.metrics.reference_response_jitter_pp_ms, ...
    baseline.metrics.fixture_observed_worst_response_ms, ...
    baseline.metrics.component_response_envelope_ms, ...
    baseline.metrics.reference_deadline_miss_count);

%% Sweep 1 - move only release-jitter amplitude
releaseAmplitudeSweepMs = [0 1 2 3];
releaseJitterPpMs = zeros(size(releaseAmplitudeSweepMs));
observedWorstResponseMs = zeros(size(releaseAmplitudeSweepMs));
worstNominalLatencyMs = zeros(size(releaseAmplitudeSweepMs));
responseJitterPpMs = zeros(size(releaseAmplitudeSweepMs));
for sweepIndex = 1:numel(releaseAmplitudeSweepMs)
    sweptInput = p12_scenario('baseline', ...
        releaseAmplitudeSweepMs(sweepIndex), 1, 20, 2, 7, 1);
    swept = runFixture(sweptInput);
    releaseJitterPpMs(sweepIndex) = ...
        swept.metrics.reference_release_jitter_pp_ms;
    observedWorstResponseMs(sweepIndex) = ...
        swept.metrics.fixture_observed_worst_response_ms;
    worstNominalLatencyMs(sweepIndex) = ...
        max(swept.reference.nominal_completion_latency_ms);
    responseJitterPpMs(sweepIndex) = ...
        swept.metrics.reference_response_jitter_pp_ms;
    assert(isequal(swept.input.execution_ms, ...
        baseline.input.execution_ms) && ...
        isequal(swept.input.blocking_ms, ...
        baseline.input.blocking_ms) && ...
        isequal(swept.input.interference_ms, ...
        baseline.input.interference_ms) && ...
        swept.input.period_ms == baseline.input.period_ms && ...
        swept.input.deadline_ms == baseline.input.deadline_ms && ...
        swept.input.timestamp_tick_ms == ...
        baseline.input.timestamp_tick_ms && ...
        swept.input.response_timeout_ms == ...
        baseline.input.response_timeout_ms && ...
        strcmp(swept.input.timeout_action, ...
        baseline.input.timeout_action), ...
        'Release-jitter sweep must isolate its one timing input.');
end
assert(isequal(releaseJitterPpMs, [0 2 4 6]) && ...
    isequal(observedWorstResponseMs, [6 6 6 6]) && ...
    isequal(worstNominalLatencyMs, [6 7 8 9]) && ...
    isequal(responseJitterPpMs, [4 4 4 4]), ...
    'Release-amplitude sweep references changed.');

figure('Name', 'P12 release-jitter sweep');
plot(releaseAmplitudeSweepMs, releaseJitterPpMs, 'o-', ...
    'LineWidth', 1.4);
hold on;
plot(releaseAmplitudeSweepMs, observedWorstResponseMs, 's--', ...
    'LineWidth', 1.4);
plot(releaseAmplitudeSweepMs, worstNominalLatencyMs, '^-.', ...
    'LineWidth', 1.4);
hold off;
grid on;
xlabel('Release-offset amplitude (ms)');
ylabel('Jitter, response, or nominal latency (ms)');
legend({'Release jitter p-p', 'Observed worst response', ...
    'Worst nominal completion latency'}, 'Location', 'northwest');
title('Lever 1 changed view: own release offset changes L, not R=f-a');
fprintf(['Mechanism for sweep 1: j changes a relative to n, so L=j+R ' ...
    'moves while the response components B, I, and C stay fixed.\n']);

%% Sweep 2 - reset release jitter, then move only bounded blocking
blockingBudgetSweepMs = [0 1 2 3];
blockingWorstResponseMs = zeros(size(blockingBudgetSweepMs));
blockingResponseJitterPpMs = zeros(size(blockingBudgetSweepMs));
blockingReleaseJitterPpMs = zeros(size(blockingBudgetSweepMs));
deadlineMissCount = zeros(size(blockingBudgetSweepMs));
for sweepIndex = 1:numel(blockingBudgetSweepMs)
    sweptInput = p12_scenario('baseline', 1, ...
        blockingBudgetSweepMs(sweepIndex), 20, 2, 7, 1);
    swept = runFixture(sweptInput);
    blockingWorstResponseMs(sweepIndex) = ...
        swept.metrics.fixture_observed_worst_response_ms;
    blockingResponseJitterPpMs(sweepIndex) = ...
        swept.metrics.reference_response_jitter_pp_ms;
    blockingReleaseJitterPpMs(sweepIndex) = ...
        swept.metrics.reference_release_jitter_pp_ms;
    deadlineMissCount(sweepIndex) = ...
        swept.metrics.reference_deadline_miss_count;
    assert(isequal(swept.input.release_offset_ms, ...
        baseline.input.release_offset_ms) && ...
        isequal(swept.input.execution_ms, ...
        baseline.input.execution_ms) && ...
        isequal(swept.input.interference_ms, ...
        baseline.input.interference_ms) && ...
        swept.input.period_ms == baseline.input.period_ms && ...
        swept.input.deadline_ms == baseline.input.deadline_ms && ...
        swept.input.timestamp_tick_ms == ...
        baseline.input.timestamp_tick_ms && ...
        swept.input.response_timeout_ms == ...
        baseline.input.response_timeout_ms && ...
        strcmp(swept.input.timeout_action, ...
        baseline.input.timeout_action), ...
        'Blocking sweep must isolate the P11-derived blocking input.');
    assert(swept.metrics.fixture_observed_worst_response_ms <= ...
        swept.metrics.component_response_envelope_ms, ...
        'Every finite-fixture response must stay inside its component envelope.');
end
assert(isequal(blockingWorstResponseMs, [5 6 7 8]) && ...
    isequal(blockingResponseJitterPpMs, [3 4 5 6]) && ...
    isequal(blockingReleaseJitterPpMs, [2 2 2 2]) && ...
    isequal(deadlineMissCount, [0 0 0 1]), ...
    'Blocking-budget sweep references changed.');

figure('Name', 'P12 bounded-blocking sweep');
plot(blockingBudgetSweepMs, blockingWorstResponseMs, 'o-', ...
    'LineWidth', 1.4);
hold on;
plot(blockingBudgetSweepMs, blockingResponseJitterPpMs, 's--', ...
    'LineWidth', 1.4);
plot(blockingBudgetSweepMs, deadlineMissCount, '^-.', ...
    'LineWidth', 1.4);
hold off;
grid on;
xlabel('Bounded blocking input B_{max} (ms)');
ylabel('Response/jitter (ms) or misses (count)');
legend({'Observed worst response', 'Response jitter p-p', ...
    'Deadline misses'}, 'Location', 'northwest');
title('Lever 2 changed view: P11 blocking enters R, not release jitter');
fprintf(['Mechanism for sweep 2: after resetting j, each selected job ' ...
    'adds B directly to R=B+I+C; R=D passes and only R>D misses.\n']);

%% Broken case - completion spacing is mislabeled as release jitter
brokenInput = p12_scenario('completion-jitter-trap');
broken = runFixture(brokenInput);
naiveCompletionDeviationMs = ...
    broken.reference.completion_interval_deviation_ms;
naiveCompletionJitterPpMs = max(naiveCompletionDeviationMs) - ...
    min(naiveCompletionDeviationMs);
assert(all(broken.reference.release_offset_ms == 0) && ...
    broken.metrics.reference_release_jitter_pp_ms == 0 && ...
    isequal(naiveCompletionDeviationMs, [1 0 0 1 -1 0 3]) && ...
    naiveCompletionJitterPpMs == 4, ...
    ['The broken case must show nonzero completion-spacing variation ' ...
    'despite exactly zero release jitter.']);
assert(isequal(broken.input.blocking_ms, ...
    baseline.input.blocking_ms) && ...
    isequal(broken.input.interference_ms, ...
    baseline.input.interference_ms) && ...
    isequal(broken.input.execution_ms, ...
    baseline.input.execution_ms), ...
    'The completion-jitter trap must retain the response workload.');

figure('Name', 'P12 deliberately broken completion-jitter proxy');
stem(2:broken.input.job_count, naiveCompletionDeviationMs, ...
    'filled', 'LineWidth', 1.3);
hold on;
plot(1:broken.input.job_count, ...
    broken.reference.release_offset_ms, 's--', 'LineWidth', 1.3);
hold off;
grid on;
xlabel('Job (index)');
ylabel('Timing deviation (ms)');
legend({'Completion interval - period', 'True release offset'}, ...
    'Location', 'northwest');
title('Broken assumption: completion spacing equals release jitter');
disp(['Broken symptom: delta-f minus period also contains delta-R. ' ...
    'Measure a-n for release jitter and f-a for response.']);

recovered = runFixture(input);
assert(isequaln(recovered, baseline), ...
    'Restoring the baseline measurement must recover exact state.');

%% Coarse clock, observation timeout, cancellation, and recovery
coarseInput = p12_scenario('coarse-clock');
coarse = runFixture(coarseInput);
assert(isequal(coarse.reference.response_ms, ...
    [2 3 3 3 4 3 3 6]) && ...
    isequal(coarse.measurement.response_ms, ...
    [0 4 0 4 4 4 0 8]) && ...
    coarse.metrics.fixture_observed_worst_response_ms == 6 && ...
    coarse.metrics.measured_observed_worst_response_ms == 8, ...
    'Coarse timestamp quantization diagnostic changed.');

exactBoundaryInput = input;
exactBoundaryInput.response_timeout_ms = 6;
exactBoundaryInput.timeout_action = 'cancel-observation';
exactBoundary = runFixture(exactBoundaryInput);
assert(exactBoundary.metrics.timeout_count == 0 && ...
    exactBoundary.metrics.censored_count == 0 && ...
    exactBoundary.metrics.measured_observed_worst_is_complete_trace, ...
    'Response equal to the timeout boundary must remain retained.');

continueInput = p12_scenario('timeout-continue');
continued = runFixture(continueInput);
assert(continued.metrics.timeout_count == 1 && ...
    continued.metrics.censored_count == 0 && ...
    continued.metrics.retained_count == 8 && ...
    continued.metrics.measured_observed_worst_response_ms == 6 && ...
    continued.metrics.measured_observed_worst_is_complete_trace, ...
    'Continue-observing must retain the timed-out response sample.');

cancelInput = p12_scenario('timeout-cancel');
cancelled = runFixture(cancelInput);
assert(cancelled.metrics.timeout_count == 1 && ...
    cancelled.metrics.censored_count == 1 && ...
    cancelled.metrics.retained_count == 7 && ...
    cancelled.metrics.measured_observed_worst_response_ms == 4 && ...
    cancelled.metrics.incomplete_observed_worst_lower_bound_ms == 5 && ...
    ~cancelled.metrics.measured_observed_worst_is_complete_trace && ...
    isnan(cancelled.measurement.response_ms(8)) && ...
    cancelled.timeline.completion_ms(8) == ...
    baseline.timeline.completion_ms(8), ...
    'Observation cancellation must censor, not alter, the rare tail job.');
rollback = runFixture(input);
assert(isequaln(rollback, baseline), ...
    'A clean call after timeout and cancellation must recover baseline.');

disp(['A censored maximum is incomplete; 4 ms cannot replace the known ' ...
    '5 ms lower bound or the fixture reference of 6 ms.']);
disp(['P12 uses deterministic synthetic timestamps. It is not ' ...
    'MATLAB-runtime, RTOS, processor, hardware, bench, HIL, field, or ' ...
    'production evidence, and a finite trace is not a WCRT guarantee.']);
