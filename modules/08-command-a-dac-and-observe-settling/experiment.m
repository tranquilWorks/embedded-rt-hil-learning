%% P08 - Command a DAC and Observe Settling
% Read: P07 separated analog input behavior from the meaning of sampled
% codes. P08 follows the reverse path: a valid command code selects a held
% target, but it does not prove that the analog output has settled.
close all;

%% Baseline - quantize, latch, and settle one deterministic DAC step
input = p08_scenario('baseline');
baseline = model(input.command_voltage_v, input.initial_voltage_v, ...
    input.reference_voltage_v, input.dac_bits, ...
    input.update_latency_s, input.time_constant_s, ...
    input.slew_rate_v_per_s, input.tolerance_v, ...
    input.sample_period_s, input.sample_count, input.fault, ...
    input.command_deadline_s);
baselineRepeat = model(input.command_voltage_v, input.initial_voltage_v, ...
    input.reference_voltage_v, input.dac_bits, ...
    input.update_latency_s, input.time_constant_s, ...
    input.slew_rate_v_per_s, input.tolerance_v, ...
    input.sample_period_s, input.sample_count, input.fault, ...
    input.command_deadline_s);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic DAC baseline changed between identical calls.');
assert(baseline.quantizer.level_count == 4096 && ...
    baseline.quantizer.initial_code == 621 && ...
    baseline.quantizer.command_code == 3103, ...
    'The baseline must retain its declared 12-bit initial and command codes.');
assert(abs(baseline.quantizer.command_voltage_v - ...
    2.4999755859375) < 1e-15, ...
    'The code 3103 target must equal code times V_ref/4096.');
assert(baseline.command.digital_complete && ...
    baseline.command.output_update_applied && ...
    ~baseline.command.timed_out, ...
    'The baseline command must update the output at 100 us.');
assert(baseline.settling.slew_limited && ...
    abs(baseline.settling.slew_duration_s - ...
    249.91455078125e-6) < 1e-15, ...
    'The baseline large step must retain its exact slew duration.');
assert(abs(baseline.settling.analytic_after_update_s - ...
    1.401207097278273e-3) < 1e-15 && ...
    abs(baseline.settling.sampled_first_stay_time_s - 1.505e-3) < 1e-15, ...
    'Analytic and 5 us-grid settling observations must remain distinct.');

figure('Name', 'P08 baseline held target and analog response');
stairs(1000 .* baseline.response.time_s, ...
    baseline.response.held_target_v, 'k--', 'LineWidth', 1.2);
hold on;
plot(1000 .* baseline.response.time_s, baseline.response.output_v, ...
    'b-', 'LineWidth', 1.5);
plot(1000 .* baseline.command.scheduled_update_time_s .* [1 1], ...
    [0 input.reference_voltage_v], 'r:', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Time (ms)');
ylabel('Voltage (V)');
legend({'Zero-order-held target', 'Analog output', 'Update event'}, ...
    'Location', 'southeast');
title('Baseline view 1: code update precedes analog settling');

figure('Name', 'P08 baseline code, error, and tolerance views');
subplot(2, 1, 1);
stairs(1000 .* baseline.response.time_s, baseline.response.held_code, ...
    'k-', 'LineWidth', 1.3);
grid on;
xlabel('Time (ms)');
ylabel('Active DAC code (count)');
title('Baseline view 2: the active code is a zero-order hold');
subplot(2, 1, 2);
semilogy(1000 .* baseline.response.time_s, ...
    1000 .* max(baseline.response.intended_error_v, eps), ...
    'b-', 'LineWidth', 1.3);
hold on;
plot(1000 .* baseline.response.time_s, ...
    1000 .* input.tolerance_v .* ones(size(baseline.response.time_s)), ...
    'r--', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Time (ms)');
ylabel('Absolute target error (mV)');
legend({'Calculated error', 'Inclusive settling tolerance'}, ...
    'Location', 'southwest');
title('Entry and stay occurs on the exponential tail');

fprintf(['Baseline metrics: LSB %.6f mV, codes %d to %d, update %.0f us, ' ...
    'slew handoff %.3f us, analytic settle %.3f us after update, and ' ...
    'sampled stay %.3f ms after command.\n'], ...
    1000 .* baseline.quantizer.lsb_v, ...
    baseline.quantizer.initial_code, baseline.quantizer.command_code, ...
    1e6 .* baseline.command.scheduled_update_time_s, ...
    1e6 .* baseline.settling.slew_duration_s, ...
    1e6 .* baseline.settling.analytic_after_update_s, ...
    1000 .* baseline.settling.sampled_first_stay_time_s);

%% Sweep 1 - time constant moves the exponential settling tail
timeConstantSweepS = [100 250 500 1000 2000] .* 1e-6;
timeConstantSettlingUs = zeros(size(timeConstantSweepS));
timeConstantSlewUs = zeros(size(timeConstantSweepS));
for sweepIndex = 1:numel(timeConstantSweepS)
    swept = model(input.command_voltage_v, input.initial_voltage_v, ...
        input.reference_voltage_v, input.dac_bits, ...
        input.update_latency_s, timeConstantSweepS(sweepIndex), ...
        input.slew_rate_v_per_s, input.tolerance_v, ...
        input.sample_period_s, input.sample_count, input.fault, Inf);
    timeConstantSettlingUs(sweepIndex) = ...
        1e6 .* swept.settling.analytic_after_update_s;
    timeConstantSlewUs(sweepIndex) = 1e6 .* swept.settling.slew_duration_s;
    assert(swept.quantizer.command_code == ...
        baseline.quantizer.command_code && ...
        swept.quantizer.command_voltage_v == ...
        baseline.quantizer.command_voltage_v && ...
        swept.command.scheduled_update_time_s == ...
        baseline.command.scheduled_update_time_s && ...
        swept.input.slew_rate_v_per_s == ...
        baseline.input.slew_rate_v_per_s && ...
        swept.input.tolerance_v == baseline.input.tolerance_v, ...
        'The time-constant lever must not mutate code, latency, slew, or tolerance.');
end
assert(all(diff(timeConstantSettlingUs) > 0), ...
    'Increasing time constant must increase baseline analytic settling time.');

figure('Name', 'P08 time-constant sweep');
plot(1e6 .* timeConstantSweepS, timeConstantSettlingUs, ...
    'o-', 'LineWidth', 1.4);
hold on;
plot(1e6 .* timeConstantSweepS, timeConstantSlewUs, ...
    's--', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Output time constant (us)');
ylabel('Settling time (us)');
legend({'Tolerance entry after update', 'Slew-limited interval'}, ...
    'Location', 'northwest');
title('Lever 1 changed view: a slower pole lengthens the tail');
fprintf(['Mechanism for sweep 1: tau changes de/dt=-e/tau while the ' ...
    'quantized code, latch latency, slew cap, and tolerance stay fixed.\n']);

%% Sweep 2 - slew rate changes the large-signal ramp after resetting tau
slewRateSweepVPerS = [Inf 8000 4000 2000 1000];
slewRateSettlingUs = zeros(size(slewRateSweepVPerS));
slewRateHandoffUs = zeros(size(slewRateSweepVPerS));
for sweepIndex = 1:numel(slewRateSweepVPerS)
    swept = model(input.command_voltage_v, input.initial_voltage_v, ...
        input.reference_voltage_v, input.dac_bits, ...
        input.update_latency_s, input.time_constant_s, ...
        slewRateSweepVPerS(sweepIndex), input.tolerance_v, ...
        input.sample_period_s, input.sample_count, input.fault, Inf);
    slewRateSettlingUs(sweepIndex) = ...
        1e6 .* swept.settling.analytic_after_update_s;
    slewRateHandoffUs(sweepIndex) = 1e6 .* swept.settling.slew_duration_s;
    assert(swept.quantizer.command_code == ...
        baseline.quantizer.command_code && ...
        swept.quantizer.command_voltage_v == ...
        baseline.quantizer.command_voltage_v && ...
        swept.command.scheduled_update_time_s == ...
        baseline.command.scheduled_update_time_s && ...
        swept.input.time_constant_s == baseline.input.time_constant_s && ...
        swept.input.tolerance_v == baseline.input.tolerance_v, ...
        'The slew-rate lever must not mutate code, latency, pole, or tolerance.');
end
assert(all(diff(slewRateSettlingUs) >= 0), ...
    'Lowering the ordered slew-rate sweep must not shorten settling time.');

figure('Name', 'P08 slew-rate sweep');
plot(1:numel(slewRateSweepVPerS), slewRateSettlingUs, ...
    'o-', 'LineWidth', 1.4);
hold on;
plot(1:numel(slewRateSweepVPerS), slewRateHandoffUs, ...
    's--', 'LineWidth', 1.1);
hold off;
grid on;
set(gca, 'XTick', 1:numel(slewRateSweepVPerS), ...
    'XTickLabel', {'Inf', '8000', '4000', '2000', '1000'});
xlabel('Slew rate (V/s)');
ylabel('Settling time (us)');
legend({'Tolerance entry after update', 'Slew-limited interval'}, ...
    'Location', 'northwest');
title('Lever 2 changed view: a lower slope cap extends the ramp');
fprintf(['Mechanism for sweep 2: reset tau to 250 us, then cap |dy/dt|. ' ...
    'The handoff occurs when remaining error equals S*tau.\n']);

%% Broken case - a recorded command does not prove the output latch changed
brokenInput = p08_scenario('update-not-latched');
broken = model(brokenInput.command_voltage_v, ...
    brokenInput.initial_voltage_v, brokenInput.reference_voltage_v, ...
    brokenInput.dac_bits, brokenInput.update_latency_s, ...
    brokenInput.time_constant_s, brokenInput.slew_rate_v_per_s, ...
    brokenInput.tolerance_v, brokenInput.sample_period_s, ...
    brokenInput.sample_count, brokenInput.fault, ...
    brokenInput.command_deadline_s);
assert(broken.command.digital_complete && ...
    broken.command.recorded_code == broken.quantizer.command_code && ...
    ~broken.command.output_update_applied, ...
    'The broken digital record must exist while the output update is absent.');
assert(all(broken.response.held_code == broken.quantizer.initial_code) && ...
    all(broken.response.output_v == broken.quantizer.initial_voltage_v) && ...
    ~broken.settling.settled_within_observation, ...
    'An update not latched must leave the active code and analog output unchanged.');

deadlineInput = p08_scenario('deadline');
deadlineCase = model(deadlineInput.command_voltage_v, ...
    deadlineInput.initial_voltage_v, deadlineInput.reference_voltage_v, ...
    deadlineInput.dac_bits, deadlineInput.update_latency_s, ...
    deadlineInput.time_constant_s, deadlineInput.slew_rate_v_per_s, ...
    deadlineInput.tolerance_v, deadlineInput.sample_period_s, ...
    deadlineInput.sample_count, deadlineInput.fault, ...
    deadlineInput.command_deadline_s);
assert(deadlineCase.command.timed_out && ...
    isempty(deadlineCase.command.recorded_code) && ...
    ~deadlineCase.command.output_update_applied && ...
    all(deadlineCase.response.held_code == ...
    deadlineCase.quantizer.initial_code), ...
    'A 50 us deadline must reject a 100 us update without moving the output.');

recovered = model(input.command_voltage_v, input.initial_voltage_v, ...
    input.reference_voltage_v, input.dac_bits, ...
    input.update_latency_s, input.time_constant_s, ...
    input.slew_rate_v_per_s, input.tolerance_v, ...
    input.sample_period_s, input.sample_count, [], []);
assert(isequaln(recovered, baseline), ...
    'Removing fault and deadline inputs must exactly recover the baseline.');

figure('Name', 'P08 deliberately broken update latch');
stairs(1000 .* broken.response.time_s, ...
    broken.quantizer.command_voltage_v .* ...
    ones(size(broken.response.time_s)), 'r--', 'LineWidth', 1.1);
hold on;
stairs(1000 .* broken.response.time_s, broken.response.held_target_v, ...
    'k-', 'LineWidth', 1.3);
plot(1000 .* broken.response.time_s, broken.response.output_v, ...
    'b-', 'LineWidth', 1.5);
hold off;
grid on;
xlabel('Time (ms)');
ylabel('Voltage (V)');
legend({'Recorded command target', 'Active held target', 'Analog output'}, ...
    'Location', 'eastoutside');
title('Broken assumption: a digital record proves output-latch activity');

figure('Name', 'P08 command deadline rejection');
stairs(1e6 .* deadlineCase.response.time_s, ...
    deadlineCase.response.held_code, 'k-', 'LineWidth', 1.3);
grid on;
xlabel('Time (us)');
ylabel('Active DAC code (count)');
title('A rejected command exposes no code and leaves the output unchanged');

fprintf(['Broken-case explanation: the synthetic digital record contains ' ...
    'code %d, but the update-not-latched fault leaves active code %d and ' ...
    'the analog output unchanged. This is not a hardware measurement.\n'], ...
    broken.quantizer.command_code, broken.quantizer.initial_code);
