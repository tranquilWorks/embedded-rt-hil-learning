    all(justShort.response.output_v == ...
    justShort.quantizer.initial_voltage_v), ...
    'A timed-out command must not move the active code or analog output.');

zeroDeadline = model(2.5, 0.5, 3.3, 12, 100e-6, ...
    250e-6, 4000, 0.01, 5e-6, 601, [], 0);
assert(zeroDeadline.command.timed_out && ...
    isempty(zeroDeadline.command.recorded_voltage_v), ...
    'A zero deadline must reject a positive-latency command result.');

retryAfterTimeout = model(2.5, 0.5, 3.3, 12, 100e-6, ...
    250e-6, 4000, 0.01, 5e-6, 601, [], Inf);
assert(isequaln(retryAfterTimeout, clean), ...
    'A clean retry after timeout must recover the exact baseline.');
