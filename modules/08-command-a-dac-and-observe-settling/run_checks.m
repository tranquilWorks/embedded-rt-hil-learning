function run_checks
%RUN_CHECKS Independent deterministic and limiting-case checks for P08.

%% Exact baseline transfer, latch, response, and settling identities
fixture = p08_scenario('baseline');
clean = model(fixture.command_voltage_v, fixture.initial_voltage_v, ...
    fixture.reference_voltage_v, fixture.dac_bits, ...
    fixture.update_latency_s, fixture.time_constant_s, ...
    fixture.slew_rate_v_per_s, fixture.tolerance_v, ...
    fixture.sample_period_s, fixture.sample_count, fixture.fault, ...
    fixture.command_deadline_s);
assert(isequal(clean.response.time_s, (0:600) .* 5e-6), ...
    'Baseline trace must retain exact t_n=n*T_s sample instants.');
assert(clean.response.time_s(end) == 0.003, ...
    'Six hundred 5 us intervals must span exactly 3 ms.');
assert(clean.quantizer.level_count == 4096 && ...
    clean.quantizer.max_code == 4095, ...
    'Twelve DAC bits must define 4096 levels and maximum code 4095.');
assert(clean.quantizer.lsb_v == 3.3 ./ 4096, ...
    'The declared unipolar LSB must equal 3.3/4096 V.');
assert(clean.quantizer.initial_code == 621 && ...
    clean.quantizer.command_code == 3103, ...
    'Nearest-code quantization must retain baseline codes 621 and 3103.');
assert(clean.quantizer.initial_voltage_v == ...
    621 .* clean.quantizer.lsb_v && ...
    clean.quantizer.command_voltage_v == ...
    3103 .* clean.quantizer.lsb_v, ...
    'Baseline code voltages must equal code times LSB exactly.');
assert(abs(clean.quantizer.initial_quantization_error_v) < ...
    clean.quantizer.lsb_v ./ 2 && ...
    abs(clean.quantizer.command_quantization_error_v) < ...
    clean.quantizer.lsb_v ./ 2, ...
    'In-range nearest-code errors must remain within half an LSB.');
assert(clean.command.digital_complete && ...
    clean.command.output_update_applied && ...
    ~clean.command.timed_out && ...
    clean.command.recorded_code == 3103, ...
    'The infinite-deadline baseline must record and apply code 3103.');

beforeUpdate = clean.response.time_s < fixture.update_latency_s;
atAndAfterUpdate = clean.response.time_s >= fixture.update_latency_s;
assert(all(clean.response.held_code(beforeUpdate) == 621) && ...
    all(clean.response.held_code(atAndAfterUpdate) == 3103), ...
    'The active code must remain initial before update and then hold command.');
updateIndex = find(clean.response.time_s == fixture.update_latency_s, 1);
assert(~isempty(updateIndex) && ...
    clean.response.output_v(updateIndex) == ...
    clean.quantizer.initial_voltage_v, ...
    'The analog output must remain continuous at the ideal latch event.');
assert(clean.settling.step_magnitude_v == 1.999658203125 && ...
    abs(clean.settling.natural_initial_slope_v_per_s - ...
    7998.6328125) < 1e-10, ...
    'The quantized step and natural initial slope must be independent identities.');
assert(clean.settling.slew_limited && ...
    abs(clean.settling.slew_duration_s - ...
    249.91455078125e-6) < 1e-15, ...
    'The baseline must cross its large-signal slew threshold at the exact time.');
expectedSettlingAfterUpdateS = clean.settling.slew_duration_s + ...
    fixture.time_constant_s .* log((fixture.slew_rate_v_per_s .* ...
    fixture.time_constant_s) ./ fixture.tolerance_v);
assert(abs(clean.settling.analytic_after_update_s - ...
    expectedSettlingAfterUpdateS) < 1e-15, ...
    'The slew-to-exponential settling equation must match independently.');
assert(abs(clean.settling.analytic_from_command_s - ...
    1.501207097278273e-3) < 1e-15, ...
    'Command-to-settling time must add the exact 100 us latch latency.');
assert(abs(clean.settling.sampled_first_stay_time_s - 1.505e-3) < ...
    1e-15 && clean.settling.settled_within_observation, ...
    'The 5 us grid must first retain the settling boundary at 1.505 ms.');
sampledStayIndex = find(clean.response.stays_in_tolerance, 1, 'first');
assert(sampledStayIndex == find(clean.response.time_s == 1.505e-3, 1) && ...
    all(clean.response.in_tolerance(sampledStayIndex:end)), ...
    'Sampled settling must mean entry and stay, not one isolated band hit.');
assert(clean.settling.final_error_v < fixture.tolerance_v, ...
    'The baseline final error must be inside its inclusive tolerance.');

%% DAC code, rail, equal-code, and observation limiting cases
lowRail = model(0, 0, 3.3, 12, 0, 250e-6, Inf, ...
    0.01, 5e-6, 2);
assert(lowRail.quantizer.command_code == 0 && ...
    lowRail.quantizer.command_voltage_v == 0, ...
    'A zero-volt command must produce code zero at the low rail.');
assert(all(lowRail.response.output_v == 0) && ...
    lowRail.settling.analytic_after_update_s == 0, ...
    'A zero step must stay constant and settle at the update.');

halfScale = model(1.65, 0, 3.3, 12, 0, 250e-6, Inf, ...
    0.01, 5e-6, 2);
assert(halfScale.quantizer.command_code == 2048 && ...
    halfScale.quantizer.command_voltage_v == 1.65, ...
    'An exact half-scale command must map to half-scale code 2048.');

highRail = model(3.3, 0, 3.3, 12, 0, 250e-6, Inf, ...
    0.01, 5e-6, 2);
assert(highRail.quantizer.command_raw_code == 4096 && ...
    highRail.quantizer.command_code == 4095 && ...
    highRail.quantizer.command_saturated, ...
    'A full-scale command must clamp to the maximum code at the high rail.');
assert(highRail.quantizer.command_voltage_v == ...
    3.3 - highRail.quantizer.lsb_v, ...
    'The maximum code voltage must be one LSB below V_ref.');

sameCode = model(0.5001, 0.5, 3.3, 12, 100e-6, ...
    250e-6, 4000, 0.01, 5e-6, 100);
assert(sameCode.quantizer.initial_code == ...
    sameCode.quantizer.command_code && ...
    sameCode.settling.step_magnitude_v == 0, ...
    'Requests that quantize to one code must produce no analog step.');
assert(sameCode.settling.analytic_after_update_s == 0 && ...
    sameCode.settling.sampled_first_stay_time_s == 100e-6, ...
    'An equal-code command must settle at the latch event.');

wideTolerance = model(2.5, 0.5, 3.3, 12, 100e-6, ...
    250e-6, 4000, 3.3, 5e-6, 100);
assert(wideTolerance.settling.analytic_after_update_s == 0 && ...
    wideTolerance.settling.sampled_first_stay_time_s == 100e-6, ...
    'A tolerance wider than the step must accept the exact update boundary.');

betweenSamples = model(2.5, 0.5, 3.3, 12, 102.5e-6, ...
    250e-6, 4000, 0.01, 5e-6, 601);
firstActiveIndex = find(betweenSamples.response.held_code == ...
    betweenSamples.quantizer.command_code, 1);
assert(betweenSamples.response.time_s(firstActiveIndex) == 105e-6 && ...
    betweenSamples.command.scheduled_update_time_s == 102.5e-6, ...
    'A between-sample latch must retain analytical time and sampled observation separately.');

beyondHorizon = model(2.5, 0.5, 3.3, 12, 1, ...
    250e-6, 4000, 0.01, 5e-6, 10);
assert(beyondHorizon.command.digital_complete && ...
    beyondHorizon.command.output_update_applied && ...
    ~beyondHorizon.command.update_observed, ...
    'An accepted update beyond the trace horizon must be complete but unobserved.');
assert(all(beyondHorizon.response.output_v == ...
    beyondHorizon.quantizer.initial_voltage_v) && ...
    ~beyondHorizon.settling.settled_within_observation, ...
    'A short observation must not invent an update or sampled settling event.');

%% Pure first-order, exact slew handoff, and tolerance boundaries
pole = model(2.5, 2.25, 3.3, 12, 0, 250e-6, Inf, ...
    1e-6, 250e-6, 3);
poleDistanceV = pole.settling.step_magnitude_v;
assert(~pole.settling.slew_limited && ...
    abs(pole.response.output_v(2) - ...
    (pole.quantizer.command_voltage_v - poleDistanceV ./ exp(1))) < 1e-14, ...
    'After one time constant a pole-only step must complete about 63.2 percent.');

boundaryRateVPerS = clean.settling.step_magnitude_v ./ ...
    fixture.time_constant_s;
atSlewBoundary = model(2.5, 0.5, 3.3, 12, 0, ...
    fixture.time_constant_s, boundaryRateVPerS, fixture.tolerance_v, ...
    fixture.time_constant_s, 2);
assert(~atSlewBoundary.settling.slew_limited && ...
    abs(atSlewBoundary.response.intended_error_v(2) - ...
    clean.settling.step_magnitude_v ./ exp(1)) < 1e-14, ...
    'At S=D/tau the slew threshold must equal the pure exponential branch.');

handoffTimeS = clean.settling.slew_duration_s;
atHandoff = model(2.5, 0.5, 3.3, 12, 0, ...
    fixture.time_constant_s, fixture.slew_rate_v_per_s, ...
    fixture.tolerance_v, handoffTimeS, 2);
assert(abs(atHandoff.response.intended_error_v(end) - ...
    fixture.slew_rate_v_per_s .* fixture.time_constant_s) < 1e-14, ...
    'The slew-to-exponential response must be continuous at the handoff.');
justAfterHandoff = model(2.5, 0.5, 3.3, 12, 0, ...
    fixture.time_constant_s, fixture.slew_rate_v_per_s, ...
    fixture.tolerance_v, handoffTimeS + eps(handoffTimeS), 2);
assert(abs(justAfterHandoff.response.output_v(end) - ...
    atHandoff.response.output_v(end)) < 1e-10, ...
    'One floating-point step after handoff must not create a voltage jump.');

atSettlingBoundary = model(2.5, 0.5, 3.3, 12, 0, ...
    fixture.time_constant_s, fixture.slew_rate_v_per_s, ...
    fixture.tolerance_v, clean.settling.analytic_after_update_s, 2);
assert(atSettlingBoundary.response.intended_error_v(end) <= ...
    fixture.tolerance_v .* (1 + 1e-12), ...
    'The analytic settling boundary must enter the inclusive tolerance.');
justBeforeSettling = model(2.5, 0.5, 3.3, 12, 0, ...
    fixture.time_constant_s, fixture.slew_rate_v_per_s, ...
    fixture.tolerance_v, clean.settling.analytic_after_update_s - 1e-12, 2);
assert(justBeforeSettling.response.intended_error_v(end) > ...
    fixture.tolerance_v, ...
    'A representably earlier response time must remain outside tolerance.');

subnormalToleranceV = eps(0);
subnormalPole = model(2.5, 2.25, 3.3, 12, 0, 250e-6, Inf, ...
    subnormalToleranceV, 250e-6, 3);
expectedSubnormalPoleS = subnormalPole.input.time_constant_s .* ...
    (log(subnormalPole.settling.step_magnitude_v) - ...
    log(subnormalToleranceV));
assert(isfinite(subnormalPole.settling.analytic_after_update_s) && ...
    subnormalPole.settling.analytic_after_update_s == ...
    expectedSubnormalPoleS, ...
    ['A positive subnormal tolerance must retain a finite pole settling ' ...
    'calculation without overflowing an intermediate ratio.']);
subnormalSlew = model(2.5, 0.5, 3.3, 12, 0, 250e-6, 4000, ...
    subnormalToleranceV, 250e-6, 3);
expectedSubnormalSlewS = subnormalSlew.settling.slew_duration_s + ...
    subnormalSlew.input.time_constant_s .* ...
    (log(subnormalSlew.input.slew_rate_v_per_s .* ...
    subnormalSlew.input.time_constant_s) - log(subnormalToleranceV));
assert(isfinite(subnormalSlew.settling.analytic_after_update_s) && ...
    subnormalSlew.settling.analytic_after_update_s == ...
    expectedSubnormalSlewS, ...
    ['A positive subnormal tolerance must retain a finite hybrid settling ' ...
    'calculation without overflowing an intermediate ratio.']);

subnormalSamplePeriodS = 1e-3;
subnormalSampled = model(2.5, 2.25, 3.3, 12, 0, 250e-6, Inf, ...
    subnormalToleranceV, subnormalSamplePeriodS, 201);
expectedSubnormalSampleTimeS = ceil( ...
    subnormalSampled.settling.analytic_after_update_s ./ ...
    subnormalSamplePeriodS) .* subnormalSamplePeriodS;
subnormalStayIndex = find( ...
    subnormalSampled.response.stays_in_tolerance, 1, 'first');
assert(subnormalSampled.settling.settled_within_observation && ...
    abs(subnormalSampled.settling.sampled_first_stay_time_s - ...
    expectedSubnormalSampleTimeS) <= eps(expectedSubnormalSampleTimeS) && ...
    subnormalSampled.settling.sampled_first_stay_time_s >= ...
    subnormalSampled.settling.analytic_after_update_s, ...
    ['Subnormal sampled settling must use the remaining-error state, not ' ...
    'cancellation-prone subtraction of rounded output voltages.']);
assert(subnormalStayIndex > 1 && ...
    subnormalSampled.response.intended_error_v( ...
    subnormalStayIndex - 1) > subnormalToleranceV && ...
    subnormalSampled.response.intended_error_v(subnormalStayIndex) <= ...
    subnormalToleranceV, ...
    'The retained grid must cross the subnormal tolerance at its first stay.');

%% Time-constant and slew-rate sweeps retain independent inputs
timeConstantSweepS = [100 250 500 1000 2000] .* 1e-6;
previousSettlingS = -Inf;
for sweepIndex = 1:numel(timeConstantSweepS)
    swept = model(2.5, 0.5, 3.3, 12, 100e-6, ...
        timeConstantSweepS(sweepIndex), 4000, 0.01, 5e-6, 601);
    assert(swept.quantizer.command_code == 3103 && ...
        swept.command.scheduled_update_time_s == 100e-6 && ...
        swept.input.slew_rate_v_per_s == 4000 && ...
        swept.input.tolerance_v == 0.01, ...
        'Time-constant sweep must isolate its pole lever.');
    assert(swept.settling.analytic_after_update_s > previousSettlingS, ...
        'Increasing time constant must lengthen this fixture settling time.');
    previousSettlingS = swept.settling.analytic_after_update_s;
end

slewRateSweepVPerS = [Inf 8000 4000 2000 1000];
previousSettlingS = -Inf;
for sweepIndex = 1:numel(slewRateSweepVPerS)
    swept = model(2.5, 0.5, 3.3, 12, 100e-6, 250e-6, ...
        slewRateSweepVPerS(sweepIndex), 0.01, 5e-6, 601);
    assert(swept.quantizer.command_code == 3103 && ...
        swept.command.scheduled_update_time_s == 100e-6 && ...
        swept.input.time_constant_s == 250e-6 && ...
        swept.input.tolerance_v == 0.01, ...
        'Slew-rate sweep must isolate its large-signal lever.');
    assert(swept.settling.analytic_after_update_s >= previousSettlingS, ...
        'Lowering the ordered slew rate must not shorten settling time.');
    previousSettlingS = swept.settling.analytic_after_update_s;
end

