title('Broken assumption: smooth samples uniquely identify the source');
subplot(2, 1, 2);
stairs(0:(input.sample_count - 1), lowPhysical.adc.codes, ...
    'k-', 'LineWidth', 1.2);
grid on;
xlabel('Sample index n');
ylabel('ADC code (count)');
title('Both physical inputs produce the same codes at every sample instant');

fprintf(['Broken-case explanation: with the analog filter bypassed, ' ...
    '820 Hz folds to signed -180 Hz at 1 ksample/s. The 180 Hz and ' ...
    '820 Hz cosine samples and codes match; more bits and a faster bus ' ...
    'cannot recover information lost before conversion.\n']);
