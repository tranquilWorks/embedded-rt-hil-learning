%% P07 - Sample an ADC Without Aliasing
% Read: P06 counted the bus cells needed to transport returned register
% bytes. P07 moves upstream: the analog bandwidth and sample instants decide
% whether those ADC codes still identify the physical input.
close all;

%% Baseline - condition and sample one strictly sub-Nyquist tone
input = p07_scenario('baseline');
baseline = model(input.signal_frequency_hz, input.sample_rate_hz, ...
    input.sample_count, input.amplitude_v, input.offset_v, ...
    input.phase_rad, input.anti_alias_cutoff_hz, input.adc_bits, ...
    input.reference_voltage_v, input.fault, ...
    input.acquisition_deadline_s);
baselineRepeat = model(input.signal_frequency_hz, input.sample_rate_hz, ...
    input.sample_count, input.amplitude_v, input.offset_v, ...
    input.phase_rad, input.anti_alias_cutoff_hz, input.adc_bits, ...
    input.reference_voltage_v, input.fault, ...
    input.acquisition_deadline_s);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic ADC baseline changed between identical calls.');
assert(baseline.frequency.nyquist_hz == 500 && ...
    baseline.frequency.nyquist_margin_hz == 320 && ...
    baseline.frequency.alias_frequency_hz == 180 && ...
    baseline.frequency.strict_nyquist_safe, ...
    'The baseline must retain a 180 Hz input below a 500 Hz Nyquist boundary.');
assert(baseline.frequency.max_alias_identity_error_v < 1e-10, ...
    'Signed folding must reproduce every conditioned sample.');
assert(baseline.adc.clipped_count == 0 && baseline.capture.complete && ...
    numel(baseline.adc.committed_codes) == input.sample_count, ...
    'The clean baseline must commit 51 unclipped ADC codes.');
assert(baseline.capture.raw_payload_rate_bps == 12000, ...
    'A 1 ksample/s, 12-bit stream offers 12000 raw payload bit/s.');

figure('Name', 'P07 baseline physical and sampled views');
subplot(2, 1, 1);
plot(1000 .* baseline.analog.reference_time_s, ...
    baseline.analog.source_v, 'Color', [0.65 0.65 0.65], ...
    'LineWidth', 1.1);
hold on;
plot(1000 .* baseline.analog.reference_time_s, ...
    baseline.analog.filtered_v, 'b-', 'LineWidth', 1.4);
plot(1000 .* baseline.samples.time_s, ...
    baseline.adc.code_center_v, 'ko', 'MarkerFaceColor', 'w');
hold off;
grid on;
xlabel('Time (ms)');
ylabel('Voltage (V)');
legend({'Physical input', 'After analog low-pass', ...
    'ADC code-center samples'}, 'Location', 'eastoutside');
title('Baseline view 1: sample instants follow analog conditioning');

subplot(2, 1, 2);
stairs(0:(input.sample_count - 1), baseline.adc.codes, ...
    'k-', 'LineWidth', 1.2);
grid on;
xlabel('Sample index n');
ylabel('ADC code (count)');
title(sprintf([ ...
    'Baseline view 2: 12-bit codes, LSB %.3f mV, no clipping'], ...
    1000 .* baseline.adc.lsb_v));

figure('Name', 'P07 baseline frequency and error metrics');
subplot(2, 1, 1);
bar([baseline.input.signal_frequency_hz ...
    baseline.frequency.alias_frequency_hz]);
set(gca, 'XTickLabel', {'Physical input', 'Sampled apparent'});
grid on;
ylabel('Frequency (Hz)');
title('Strictly sub-Nyquist input retains its apparent frequency');
subplot(2, 1, 2);
plot(0:(input.sample_count - 1), ...
    1000 .* baseline.adc.quantization_error_v, 'o-', ...
    'LineWidth', 1.1);
grid on;
xlabel('Sample index n');
ylabel('Quantization error (mV)');
title('Quantization changes voltage resolution, not the fold frequency');

fprintf(['Baseline metrics: f_in %.0f Hz, f_N %.0f Hz, margin %.0f Hz, ' ...
    'filter gain %.3f, LSB %.3f mV, and raw payload rate %.0f bit/s.\n'], ...
    baseline.input.signal_frequency_hz, baseline.frequency.nyquist_hz, ...
    baseline.frequency.nyquist_margin_hz, baseline.filter.gain, ...
    1000 .* baseline.adc.lsb_v, baseline.capture.raw_payload_rate_bps);

%% Sweep 1 - sample rate moves the Nyquist boundary and fold
sampleRateSweepHz = [1000 600 400 300 250];
aliasSweepHz = zeros(size(sampleRateSweepHz));
marginSweepHz = zeros(size(sampleRateSweepHz));
safeSweep = false(size(sampleRateSweepHz));
payloadRateSweepBps = zeros(size(sampleRateSweepHz));
for sweepIndex = 1:numel(sampleRateSweepHz)
    swept = model(input.signal_frequency_hz, ...
        sampleRateSweepHz(sweepIndex), input.sample_count, ...
        input.amplitude_v, input.offset_v, input.phase_rad, ...
        input.anti_alias_cutoff_hz, input.adc_bits, ...
        input.reference_voltage_v, input.fault, Inf);
    aliasSweepHz(sweepIndex) = swept.frequency.alias_frequency_hz;
    marginSweepHz(sweepIndex) = swept.frequency.nyquist_margin_hz;
    safeSweep(sweepIndex) = swept.frequency.strict_nyquist_safe;
    payloadRateSweepBps(sweepIndex) = ...
        swept.capture.raw_payload_rate_bps;
    assert(swept.input.signal_frequency_hz == ...
        baseline.input.signal_frequency_hz && ...
        swept.input.amplitude_v == baseline.input.amplitude_v && ...
        swept.input.anti_alias_cutoff_hz == ...
        baseline.input.anti_alias_cutoff_hz && ...
        swept.input.adc_bits == baseline.input.adc_bits, ...
        'The sample-rate lever must not mutate the source, filter, or ADC.');
end
assert(isequal(aliasSweepHz, [180 180 180 120 70]) && ...
    isequal(safeSweep, [true true true false false]), ...
    'Sample-rate sweep folds 180 Hz only after the strict boundary is crossed.');

figure('Name', 'P07 sample-rate sweep');
subplot(2, 1, 1);
plot(sampleRateSweepHz, aliasSweepHz, 'o-', 'LineWidth', 1.3);
hold on;
plot(sampleRateSweepHz, sampleRateSweepHz ./ 2, ...
    'k--', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Sample rate f_s (Hz)');
ylabel('Frequency (Hz)');
legend({'Apparent input', 'Nyquist boundary f_s/2'}, ...
    'Location', 'northwest');
title('Lever 1 changed view: lowering f_s eventually folds the tone');
subplot(2, 1, 2);
plot(sampleRateSweepHz, marginSweepHz, 's-', 'LineWidth', 1.3);
hold on;
plot(sampleRateSweepHz, zeros(size(sampleRateSweepHz)), ...
    'k:', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Sample rate f_s (Hz)');
ylabel('Strict Nyquist margin (Hz)');
title('Negative margin marks a source component at or above f_s/2');
fprintf(['Mechanism for sweep 1: f_N=f_s/2 and ' ...
    'f_fold=mod(f_in+f_s/2,f_s)-f_s/2. The bus payload rate f_s*B ' ...
    'changes too, but transport cannot reverse a fold.\n']);

%% Sweep 2 - physical input frequency folds around a reset sample rate
signalFrequencySweepHz = [50 180 350 500 650 820 1150];
physicalSweepHz = zeros(size(signalFrequencySweepHz));
apparentSweepHz = zeros(size(signalFrequencySweepHz));
filteredAmplitudeSweepV = zeros(size(signalFrequencySweepHz));
safeFrequencySweep = false(size(signalFrequencySweepHz));
for sweepIndex = 1:numel(signalFrequencySweepHz)
    swept = model(signalFrequencySweepHz(sweepIndex), ...
        input.sample_rate_hz, input.sample_count, input.amplitude_v, ...
        input.offset_v, input.phase_rad, input.anti_alias_cutoff_hz, ...
        input.adc_bits, input.reference_voltage_v, input.fault, Inf);
    physicalSweepHz(sweepIndex) = swept.input.signal_frequency_hz;
    apparentSweepHz(sweepIndex) = swept.frequency.alias_frequency_hz;
    filteredAmplitudeSweepV(sweepIndex) = ...
        swept.filter.filtered_amplitude_v;
    safeFrequencySweep(sweepIndex) = ...
        swept.frequency.strict_nyquist_safe;
    assert(swept.input.sample_rate_hz == baseline.input.sample_rate_hz && ...
        swept.input.sample_count == baseline.input.sample_count && ...
        swept.input.adc_bits == baseline.input.adc_bits && ...
        swept.capture.raw_payload_rate_bps == ...
        baseline.capture.raw_payload_rate_bps, ...
        'The input-frequency lever must not mutate sampling or ADC settings.');
end
assert(isequal(apparentSweepHz, [50 180 350 500 350 180 150]) && ...
    isequal(safeFrequencySweep, ...
    [true true true false false false false]), ...
    'Input-frequency sweep must retain the exact fold map and strict boundary.');

figure('Name', 'P07 input-frequency sweep');
subplot(2, 1, 1);
plot(physicalSweepHz, physicalSweepHz, 'k--', 'LineWidth', 1.1);
hold on;
plot(physicalSweepHz, apparentSweepHz, 'o-', 'LineWidth', 1.3);
hold off;
grid on;
xlabel('Physical input frequency (Hz)');
ylabel('Sampled apparent frequency (Hz)');
legend({'No-fold reference', 'Observed fold'}, 'Location', 'northwest');
title('Lever 2 changed view: many physical tones share baseband frequencies');
subplot(2, 1, 2);
plot(physicalSweepHz, filteredAmplitudeSweepV, ...
    's-', 'LineWidth', 1.3);
grid on;
xlabel('Physical input frequency (Hz)');
ylabel('Amplitude after analog filter (V peak)');
title('The first-order front end attenuates before, but does not undo, sampling');
fprintf(['Mechanism for sweep 2: reset f_s to 1000 Hz, then move f_in. ' ...
    'The analog H(f)=1/(1+j f/f_c) changes amplitude and phase before ' ...
    'the signed fold; equality at f_s/2 is not a safe guard band.\n']);

%% Broken case - smooth ADC codes do not uniquely identify analog frequency
bypassFault = struct('mode', 'anti-alias-bypass');
lowPhysical = model(180, 1000, input.sample_count, input.amplitude_v, ...
    input.offset_v, 0, input.anti_alias_cutoff_hz, input.adc_bits, ...
    input.reference_voltage_v, bypassFault, Inf);
aliasInput = p07_scenario('alias-trap');
highPhysical = model(aliasInput.signal_frequency_hz, ...
    aliasInput.sample_rate_hz, aliasInput.sample_count, ...
    aliasInput.amplitude_v, aliasInput.offset_v, aliasInput.phase_rad, ...
    aliasInput.anti_alias_cutoff_hz, aliasInput.adc_bits, ...
    aliasInput.reference_voltage_v, aliasInput.fault, ...
    aliasInput.acquisition_deadline_s);
sharedTraceTimeS = linspace(0, min( ...
    lowPhysical.capture.observation_span_s, ...
    highPhysical.capture.observation_span_s), 2001);
lowPhysicalOnSharedGridV = lowPhysical.input.offset_v + ...
    lowPhysical.input.amplitude_v .* cos(2 .* pi .* ...
    lowPhysical.input.signal_frequency_hz .* sharedTraceTimeS + ...
    lowPhysical.input.phase_rad);
highPhysicalOnSharedGridV = highPhysical.input.offset_v + ...
    highPhysical.input.amplitude_v .* cos(2 .* pi .* ...
    highPhysical.input.signal_frequency_hz .* sharedTraceTimeS + ...
    highPhysical.input.phase_rad);
assert(lowPhysical.frequency.strict_nyquist_safe && ...
    ~highPhysical.frequency.strict_nyquist_safe && ...
    lowPhysical.frequency.alias_frequency_hz == 180 && ...
    highPhysical.frequency.alias_frequency_hz == 180, ...
    'The broken pair must map physical 180 Hz and 820 Hz to apparent 180 Hz.');
assert(max(abs(lowPhysical.samples.filtered_v - ...
    highPhysical.samples.filtered_v)) < 1e-10 && ...
    isequal(lowPhysical.adc.codes, highPhysical.adc.codes), ...
    'Bypassed 180 Hz and 820 Hz inputs must produce indistinguishable ADC codes.');
assert(max(abs(lowPhysicalOnSharedGridV - ...
    highPhysicalOnSharedGridV)) > 0.5, ...
    'Dense physical traces must reveal that the aliased sources differ.');
for bitDepth = [6 12 16]
    lowBits = model(180, 1000, input.sample_count, input.amplitude_v, ...
        input.offset_v, 0, input.anti_alias_cutoff_hz, bitDepth, ...
        input.reference_voltage_v, bypassFault, Inf);
    highBits = model(820, 1000, input.sample_count, input.amplitude_v, ...
        input.offset_v, 0, input.anti_alias_cutoff_hz, bitDepth, ...
        input.reference_voltage_v, bypassFault, Inf);
    assert(isequal(lowBits.adc.codes, highBits.adc.codes), ...
        'More ADC bits must not disambiguate an already aliased pair.');
end

deadlineInput = p07_scenario('deadline');
deadlineCase = model(deadlineInput.signal_frequency_hz, ...
    deadlineInput.sample_rate_hz, deadlineInput.sample_count, ...
    deadlineInput.amplitude_v, deadlineInput.offset_v, ...
    deadlineInput.phase_rad, deadlineInput.anti_alias_cutoff_hz, ...
    deadlineInput.adc_bits, deadlineInput.reference_voltage_v, ...
    deadlineInput.fault, deadlineInput.acquisition_deadline_s);
assert(deadlineCase.capture.timed_out && ...
    isempty(deadlineCase.adc.committed_codes), ...
    'A 50 ms policy must reject a modeled 51 ms acquisition result.');
recovered = model(input.signal_frequency_hz, input.sample_rate_hz, ...
    input.sample_count, input.amplitude_v, input.offset_v, ...
    input.phase_rad, input.anti_alias_cutoff_hz, input.adc_bits, ...
    input.reference_voltage_v, [], []);
assert(isequaln(recovered, baseline), ...
    'Removing the fault and deadline must exactly recover the baseline.');

figure('Name', 'P07 deliberately broken alias assumption');
subplot(2, 1, 1);
plot(1000 .* lowPhysical.analog.reference_time_s, ...
    lowPhysical.analog.source_v, 'b-', 'LineWidth', 1.2);
hold on;
plot(1000 .* highPhysical.analog.reference_time_s, ...
    highPhysical.analog.source_v, 'r--', 'LineWidth', 1.2);
plot(1000 .* lowPhysical.samples.time_s, ...
    lowPhysical.samples.filtered_v, 'ko', 'MarkerFaceColor', 'w');
hold off;
grid on;
xlabel('Time (ms)');
ylabel('Voltage (V)');
legend({'Physical 180 Hz', 'Physical 820 Hz', ...
