%% P16 - Execute a Multi-Rate Processing Graph
% What inputs, observable effects, and failure modes matter when you execute
% a Multi-Rate Processing Graph?
% P15 aligned timestamps into one reference coordinate. P16 uses those
% ordered, uniformly spaced timestamps to release a fast filter every sample
% and a slow frame node every D samples.
modelFcn = @model;
scenarioFcn = @p16_scenario;
runFixture = @(input) modelFcn(input.sample_value, ...
    input.sample_time_us, input.decimation_factor, ...
    input.fast_cost_us, input.slow_cost_us, ...
    input.output_timeout_us, input.timeout_action, ...
    input.execution_order);

%% Read the rate and workload rules
% The entry lesson asks one prediction about changing D before this script
% shows the baseline. Running experiment alone proceeds directly to the
% same baseline without asking a second prediction.

%% Baseline - one complete frame every four aligned samples
baselineInput = scenarioFcn('baseline');
baseline = runFixture(baselineInput);
baselineRepeat = runFixture(baselineInput);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic P16 baseline must repeat exactly.');
expectedFilteredValue = [0 0.5 1.5:1:30.5];
expectedFrameValue = [1.125 5 9 13 17 21 25 29];
expectedReleaseUs = 3000:4000:31000;
expectedFinishUs = 4300:4000:32300;
assert(isequal(baseline.fast.filtered_value, expectedFilteredValue) && ...
    isequal(baseline.frame.output_value, expectedFrameValue) && ...
    isequal(baseline.frame.release_us, expectedReleaseUs) && ...
    isequal(baseline.frame.completion_us, expectedFinishUs) && ...
    isequal(baseline.frame.output_latency_us, 1300 .* ones(1, 8)) && ...
    isequal(baseline.frame.deadline_slack_us, 700 .* ones(1, 8)) && ...
    baseline.metrics.nominal_output_rate_hz == 250 && ...
    baseline.metrics.slow_utilization_ratio == 0.3 && ...
    baseline.metrics.maximum_outstanding_depth == 1 && ...
    baseline.metrics.emitted_count == 8 && ...
    baseline.metrics.timeout_count == 0, ...
    'Baseline multi-rate reference vectors changed.');

figure('Name', 'P16 baseline data through the graph');
plot(baseline.input.sample_time_us, baseline.input.sample_value, ...
    '.-', 'LineWidth', 1.2, 'DisplayName', 'Source sample');
hold on;
plot(baseline.input.sample_time_us, baseline.fast.filtered_value, ...
    '-', 'LineWidth', 1.4, 'DisplayName', 'Fast two-sample filter');
stem(baseline.frame.expected_timestamp_us, ...
    baseline.frame.output_value, 'filled', ...
    'DisplayName', 'Slow frame mean');
hold off;
grid on;
xlabel('Aligned reference time (us)');
ylabel('Signal value (engineering unit)');
title('A D=4 frame consumes four current fast-stage values');
legend('Location', 'best');

figure('Name', 'P16 baseline timing and outstanding work');
subplot(2, 1, 1);
plot(baseline.frame.release_us, baseline.frame.output_latency_us, ...
    '-o', 'LineWidth', 1.5);
hold on;
yline(baseline.input.output_timeout_us, '--', 'Timeout');
hold off;
grid on;
xlabel('Frame release time (us)');
ylabel('Output latency (us)');
title('Every frame completes 700 us before its timeout');
subplot(2, 1, 2);
stairs(baseline.frame.release_us, ...
    baseline.frame.outstanding_depth_at_ready, 'LineWidth', 1.5);
grid on;
xlabel('Frame release time (us)');
ylabel('Outstanding slow frames (frame)');
title('Slow utilization 0.30 keeps inclusive outstanding depth at one');

fprintf(['Baseline: input=%.0f Hz, output=%.0f Hz, slow utilization=%.2f, ' ...
    'max latency=%g us, minimum slack=%g us.\n'], ...
    baseline.metrics.input_rate_hz, ...
    baseline.metrics.nominal_output_rate_hz, ...
    baseline.metrics.slow_utilization_ratio, ...
    baseline.metrics.maximum_output_latency_us, ...
    baseline.metrics.minimum_deadline_slack_us);

%% Sweep 1 - change only the decimation factor
decimationSweep = [1 2 4 8];
frameCountByDecimation = zeros(size(decimationSweep));
outputRateHz = zeros(size(decimationSweep));
slowUtilization = zeros(size(decimationSweep));
timeoutCountByDecimation = zeros(size(decimationSweep));
maximumLatencyUs = zeros(size(decimationSweep));
maximumOutstandingDepth = zeros(size(decimationSweep));
for sweepIndex = 1:numel(decimationSweep)
    sweptInput = baselineInput;
    sweptInput.decimation_factor = decimationSweep(sweepIndex);
    swept = runFixture(sweptInput);
    frameCountByDecimation(sweepIndex) = swept.metrics.frame_count;
    outputRateHz(sweepIndex) = swept.metrics.nominal_output_rate_hz;
    slowUtilization(sweepIndex) = swept.metrics.slow_utilization_ratio;
    timeoutCountByDecimation(sweepIndex) = swept.metrics.timeout_count;
    maximumLatencyUs(sweepIndex) = ...
        swept.metrics.maximum_output_latency_us;
    maximumOutstandingDepth(sweepIndex) = ...
        swept.metrics.maximum_outstanding_depth;
    assert(swept.input.fast_cost_us == baseline.input.fast_cost_us && ...
        swept.input.slow_cost_us == baseline.input.slow_cost_us && ...
        swept.input.output_timeout_us == ...
        baseline.input.output_timeout_us && ...
        strcmp(swept.input.execution_order, ...
        baseline.input.execution_order), ...
        'Decimation sweep must isolate the graph rate ratio.');
end
assert(isequal(frameCountByDecimation, [32 16 8 4]) && ...
    isequal(outputRateHz, [1000 500 250 125]) && ...
    max(abs(slowUtilization - [1.2 0.6 0.3 0.15])) < 1e-12 && ...
    isequal(timeoutCountByDecimation, [28 0 0 0]) && ...
    isequal(maximumLatencyUs, [7500 1300 1300 1300]) && ...
    isequal(maximumOutstandingDepth, [7 1 1 1]), ...
    'Decimation-factor sweep reference vectors changed.');

figure('Name', 'P16 decimation-factor sweep');
yyaxis left;
plot(decimationSweep, outputRateHz, '-o', 'LineWidth', 1.5);
ylabel('Nominal output rate (Hz)');
yyaxis right;
plot(decimationSweep, slowUtilization, '-s', 'LineWidth', 1.5);
yline(1, '--', 'Capacity');
ylabel('Slow-node utilization (ratio)');
grid on;
xlabel('Decimation factor D (sample/frame)');
title('Larger D lowers both firing rate and slow-node demand');
legend('Output rate', 'Slow utilization', 'Capacity', ...
    'Location', 'best');

%% Mechanism for sweep 1
% The slow node fires at fs/D. With fixed code cost, increasing D stretches
% the time between frame jobs; decreasing D toward one can make utilization
% exceed one and grow outstanding work even though each calculation is valid.

%% Sweep 2 - reset, then change only slow-node execution cost
slowCostSweepUs = [200 800 1200 1800 4200];
utilizationByCost = zeros(size(slowCostSweepUs));
latencyByCostUs = zeros(size(slowCostSweepUs));
minimumSlackByCostUs = zeros(size(slowCostSweepUs));
timeoutCountByCost = zeros(size(slowCostSweepUs));
outstandingDepthByCost = zeros(size(slowCostSweepUs));
for sweepIndex = 1:numel(slowCostSweepUs)
    sweptInput = baselineInput;
    sweptInput.slow_cost_us = slowCostSweepUs(sweepIndex);
    swept = runFixture(sweptInput);
    utilizationByCost(sweepIndex) = ...
        swept.metrics.slow_utilization_ratio;
    latencyByCostUs(sweepIndex) = ...
        swept.metrics.maximum_output_latency_us;
    minimumSlackByCostUs(sweepIndex) = ...
        swept.metrics.minimum_deadline_slack_us;
    timeoutCountByCost(sweepIndex) = swept.metrics.timeout_count;
    outstandingDepthByCost(sweepIndex) = ...
        swept.metrics.maximum_outstanding_depth;
    assert(swept.input.decimation_factor == ...
        baseline.input.decimation_factor && ...
        swept.input.fast_cost_us == baseline.input.fast_cost_us && ...
        swept.input.output_timeout_us == ...
        baseline.input.output_timeout_us && ...
        strcmp(swept.input.execution_order, ...
        baseline.input.execution_order), ...
        'Slow-cost sweep must reset and isolate slow-node work.');
end
assert(max(abs(utilizationByCost - [0.05 0.2 0.3 0.45 1.05])) < ...
    1e-12 && ...
    isequal(latencyByCostUs, [300 900 1300 1900 5700]) && ...
    isequal(minimumSlackByCostUs, [1700 1100 700 100 -3700]) && ...
    isequal(timeoutCountByCost, [0 0 0 0 8]) && ...
    isequal(outstandingDepthByCost, [1 1 1 1 2]), ...
    'Slow-execution-cost sweep reference vectors changed.');

figure('Name', 'P16 slow-node cost sweep');
yyaxis left;
plot(slowCostSweepUs, latencyByCostUs, '-o', 'LineWidth', 1.5);
yline(baseline.input.output_timeout_us, '--', 'Timeout');
ylabel('Maximum output latency (us)');
yyaxis right;
plot(slowCostSweepUs, utilizationByCost, '-s', 'LineWidth', 1.5);
yline(1, ':', 'Capacity');
ylabel('Slow-node utilization (ratio)');
grid on;
xlabel('Slow-node execution cost (us/frame)');
title('Execution cost consumes slack, then exceeds service capacity');
legend('Maximum latency', 'Timeout', 'Utilization', 'Capacity', ...
    'Location', 'best');

%% Mechanism for sweep 2
% Cost changes finish time without changing frame membership or nominal
% output rate. Once Cslow exceeds D*Ts, unfinished jobs carry into later
% releases; timeout is a latency boundary, not a substitute for capacity.

%% Broken case - consumer executes before the current producer result
broken = runFixture(scenarioFcn('broken-consumer-first'));
expectedBrokenValue = [NaN 4 8 12 16 20 24 28];
assert(~broken.metrics.ordering_consistent && ...
    broken.metrics.underflow_count == 1 && ...
    broken.metrics.dropped_count == 1 && ...
    broken.frame.outstanding_depth_at_ready(1) == 0 && ...
    isnan(broken.frame.ready_us(1)) && ...
    isnan(broken.frame.slow_start_us(1)) && ...
    isnan(broken.frame.scheduled_finish_us(1)) && ...
    ~broken.frame.timed_out(1) && ...
    isequaln(broken.frame.output_value, expectedBrokenValue) && ...
    isequal(broken.frame.timestamp_error_us, -1000 .* ones(1, 8)) && ...
    isequal(broken.frame.consumed_last_sample_index, [2 6 10 14 18 22 26 30]) && ...
    isequal(baseline.frame.expected_last_sample_index, [3 7 11 15 19 23 27 31]), ...
    'Broken consumer-before-producer symptom changed.');

figure('Name', 'P16 deliberately broken execution order');
plot(0:7, baseline.frame.output_value, '-o', 'LineWidth', 1.5);
hold on;
plot(0:7, broken.frame.output_value, '-s', 'LineWidth', 1.5);
plot(0, 0, 'rx', 'MarkerSize', 11, 'LineWidth', 2);
hold off;
grid on;
xlabel('Slow frame index (count)');
ylabel('Frame output (engineering unit)');
title('Broken assumption: consumer may run before its current producer');
legend('Producer first', 'Consumer first', 'Initial underflow', ...
    'Location', 'best');

%% Timeout equality, continuation, cancellation, rollback, and recovery
equalityInput = baselineInput;
equalityInput.slow_cost_us = 1900;
equalityInput.timeout_action = 'cancel-frame';
equality = runFixture(equalityInput);
continued = runFixture(scenarioFcn('timeout-continue'));
cancelled = runFixture(scenarioFcn('timeout-cancel'));
assert(equality.metrics.timeout_count == 0 && ...
    equality.metrics.cancelled_count == 0 && ...
    equality.metrics.emitted_count == 8 && ...
    isequal(equality.frame.output_latency_us, 2000 .* ones(1, 8)) && ...
    continued.metrics.timeout_count == 28 && ...
    continued.metrics.cancelled_count == 0 && ...
    continued.metrics.emitted_count == 32 && ...
    continued.metrics.maximum_outstanding_depth == 7 && ...
    cancelled.metrics.timeout_count == 28 && ...
    cancelled.metrics.cancelled_count == 28 && ...
    cancelled.metrics.emitted_count == 4 && ...
    cancelled.metrics.maximum_outstanding_depth == 2 && ...
    isequaln(continued.frame.computed_value, ...
    cancelled.frame.computed_value), ...
    'Timeout equality, continuation, or cancellation changed.');

rollback = runFixture(baselineInput);
recovered = runFixture(scenarioFcn('baseline'));
assert(isequaln(rollback, baseline) && isequaln(recovered, baseline), ...
    'Clean pure-model input must provide exact computational recovery.');

figure('Name', 'P16 timeout continuation and cancellation');
bar([continued.metrics.emitted_count, continued.metrics.cancelled_count; ...
    cancelled.metrics.emitted_count, cancelled.metrics.cancelled_count]);
grid on;
xlabel('Timeout action (case)');
ylabel('Frames (count)');
xticklabels({'continue processing', 'cancel frame'});
legend('Emitted', 'Cancelled', 'Location', 'best');
title('Cancellation bounds backlog by dropping late simulated frames');

