%% Broken case - completion does not prove correct destination addressing
brokenInput = scenarioFcn('fixed-destination');
broken = runFixture(brokenInput);
assert(isequal(broken.timeline.completion_us, ...
    baseline.timeline.completion_us) && ...
    broken.metrics.completion_interrupt_count == 4 && ...
    broken.observation.descriptor_complete, ...
    'Fixed addressing must leave apparent transfer timing healthy.');
assert(broken.memory.destination_samples(1) == 1158 && ...
    all(isnan(broken.memory.destination_samples(2:end))) && ...
    broken.metrics.written_slot_count == 1 && ...
    broken.metrics.unwritten_slot_count == 31 && ...
    broken.metrics.overwrite_count == 31 && ...
    ~broken.metrics.data_integrity, ...
    'Fixed destination must overwrite one slot and lose array integrity.');

figure('Name', 'P13 deliberately broken destination increment');
stem(broken.timeline.sample_index, broken.memory.source_samples, ...
    'filled', 'LineWidth', 1.2);
hold on;
plot(broken.timeline.sample_index, ...
    broken.memory.destination_samples, 'rx', ...
    'LineWidth', 1.5, 'MarkerSize', 8);
hold off;
grid on;
xlabel('Source or destination slot (index)');
ylabel('Synthetic sample code (count)');
legend({'Source sequence', 'Destination memory'}, ...
    'Location', 'northwest');
title('Broken assumption: completion means destination incremented');
disp(['Broken symptom: all 32 beats and four block completions occur, ' ...
    'yet 31 writes overwrite slot 1 and 31 slots remain unwritten.']);

%% Timeout, cancellation boundary, rollback, and clean recovery
boundaryInput = input;
boundaryInput.descriptor_timeout_us = 1561;
boundaryInput.timeout_action = 'abort-transfer';
boundary = runFixture(boundaryInput);
assert(~boundary.observation.wait_timed_out && ...
    ~boundary.observation.abort_issued && ...
    boundary.observation.descriptor_complete && ...
    boundary.observation.committed_sample_count == 32, ...
    'Descriptor completion exactly at timeout must pass.');

continueInput = scenarioFcn('timeout-continue');
continued = runFixture(continueInput);
assert(continued.observation.wait_timed_out && ...
    ~continued.observation.abort_issued && ...
    continued.observation.descriptor_complete && ...
    continued.observation.committed_sample_count == 32 && ...
    continued.metrics.data_integrity, ...
    'Continue-waiting must record timeout and retain the full transfer.');

abortInput = scenarioFcn('timeout-abort');
aborted = runFixture(abortInput);
assert(aborted.observation.wait_timed_out && ...
    aborted.observation.abort_issued && ...
    ~aborted.observation.descriptor_complete && ...
    aborted.observation.committed_sample_count == 24 && ...
    aborted.observation.cancelled_sample_count == 8 && ...
    aborted.observation.completed_block_count == 3 && ...
    ~aborted.observation.partial_beat_in_flight_at_abort && ...
    aborted.metrics.committed_bytes + aborted.metrics.cancelled_bytes == ...
    aborted.metrics.requested_bytes, ...
    'Abort at 1161 us must expose a 24-sample committed prefix.');

partialInput = input;
partialInput.descriptor_timeout_us = 1160;
partialInput.timeout_action = 'abort-transfer';
partialAbort = runFixture(partialInput);
assert(partialAbort.observation.committed_sample_count == 23 && ...
    partialAbort.observation.completed_block_count == 2 && ...
    partialAbort.observation.partial_beat_in_flight_at_abort && ...
    partialAbort.observation.completed_bus_service_us == 253 && ...
    partialAbort.observation.observed_bus_active_us == 263, ...
    'Abort inside beat 24 must not fabricate a completed sample or block.');

figure('Name', 'P13 abort visibility boundary');
stairs(aborted.timeline.sample_index, ...
    cumsum(aborted.memory.committed), 'LineWidth', 1.4);
hold on;
plot(aborted.timeline.sample_index, ...
    aborted.timeline.sample_index, 'k--', 'LineWidth', 1.1);
hold off;
grid on;
xlabel('Requested sample (index)');
ylabel('Committed destination samples (count)');
legend({'Committed before abort', 'Requested'}, ...
    'Location', 'northwest');
title('Abort exposes a prefix; it does not invent or roll back the tail');

recovered = runFixture(input);
assert(isequaln(recovered, baseline), ...
    'Clean state-free input must recover the exact baseline after faults.');
disp(['Computational recovery is an exact clean re-run only. Abort does ' ...
    'not stop the sample source, repair memory, flush caches, or roll ' ...
    'back a peripheral or plant.']);
