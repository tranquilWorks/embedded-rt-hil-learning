%% P13 - Move Samples with DMA
% Read: P12 separated request, start, and completion timestamps. P13 uses
% that vocabulary for each DMA beat. Predict once: if block size grows
% while the sample period and bus stay fixed, which changes first -- bus
% service per sample, completion-interrupt count, or oldest-sample latency?
close all;
modelFcn = @model;
scenarioFcn = @p13_scenario;
runFixture = @(fixture) modelFcn(fixture.source_samples, ...
    fixture.sample_period_us, fixture.bytes_per_sample, ...
    fixture.bus_rate_bytes_per_us, fixture.arbitration_us, ...
    fixture.block_samples, fixture.dma_setup_cpu_us, ...
    fixture.completion_isr_cpu_us, ...
    fixture.processor_copy_cpu_us_per_sample, ...
    fixture.descriptor_timeout_us, fixture.timeout_action, ...
    fixture.destination_mode);

%% Baseline - read request, transfer, block-ready, CPU, and memory views
input = scenarioFcn('baseline');
baseline = runFixture(input);
baselineRepeat = runFixture(input);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic DMA baseline must repeat exactly.');
assert(isequal(baseline.timeline.request_us, 0:50:1550) && ...
    isequal(baseline.timeline.start_us, 0:50:1550) && ...
    isequal(baseline.timeline.completion_us, 11:50:1561), ...
    'Baseline request/start/completion references changed.');
assert(isequal(baseline.block.end_sample_index, [8 16 24 32]) && ...
    isequal(baseline.block.completion_us, [361 761 1161 1561]), ...
    'Baseline completion-block references changed.');
expectedReadyLatencyUs = repmat(361:-50:11, 1, 4);
assert(isequal(baseline.block.ready_latency_us, ...
    expectedReadyLatencyUs) && ...
    baseline.metrics.mean_block_ready_latency_us == 186 && ...
    baseline.metrics.max_block_ready_latency_us == 361, ...
    'Baseline block-ready latency references changed.');
assert(baseline.metrics.beat_service_us == 11 && ...
    baseline.metrics.offered_bus_load_pct == 22 && ...
    baseline.metrics.peak_pending_requests == 1 && ...
    baseline.metrics.request_budget_exceed_count == 0, ...
    'Baseline DMA service or queue metrics changed.');
assert(baseline.cpu.processor_copy_demand_us == 128 && ...
    baseline.cpu.reference_dma_demand_us == 20 && ...
    baseline.cpu.reference_cpu_service_saved_us == 108, ...
    'Baseline CPU service-demand comparison changed.');
assert(baseline.metrics.data_integrity && ...
    isequal(baseline.memory.destination_samples, ...
    baseline.memory.source_samples) && ...
    baseline.metrics.overwrite_count == 0 && ...
    baseline.metrics.unwritten_slot_count == 0, ...
    'Incrementing destination must reproduce every source sample.');

figure('Name', 'P13 baseline DMA beat timing');
plot(baseline.timeline.sample_index, ...
    baseline.timeline.request_us, 'ko-', 'LineWidth', 1.2);
hold on;
plot(baseline.timeline.sample_index, ...
    baseline.timeline.start_us, 'bs--', 'LineWidth', 1.2);
plot(baseline.timeline.sample_index, ...
    baseline.timeline.completion_us, 'r.-', 'LineWidth', 1.2, ...
    'MarkerSize', 12);
hold off;
grid on;
xlabel('Sample request (index)');
ylabel('Time from descriptor arm (us)');
legend({'Request a_i', 'DMA start s_i', 'DMA finish f_i'}, ...
    'Location', 'northwest');
title('Baseline view 1: q=11 us finishes before the next 50 us request');

figure('Name', 'P13 baseline block-ready latency');
bar(baseline.timeline.sample_index, ...
    baseline.block.ready_latency_us);
grid on;
xlabel('Sample (index)');
ylabel('Request-to-block-ready latency (us)');
title('Baseline view 2: early samples wait for their completion block');

figure('Name', 'P13 baseline CPU service demand');
stairs(baseline.timeline.sample_index, ...
    baseline.cpu.processor_copy_cumulative_us, ...
    'LineWidth', 1.4);
hold on;
stairs(baseline.timeline.sample_index, ...
    baseline.cpu.reference_dma_cumulative_us, ...
    'LineWidth', 1.4);
hold off;
grid on;
xlabel('Samples moved (count)');
ylabel('Cumulative processor service demand (us)');
legend({'Processor copies each sample', 'DMA setup + block ISRs'}, ...
    'Location', 'northwest');
title('Complementary resource view: DMA moves bytes; CPU handles control');

fprintf(['Baseline: q=%.0f us/beat, offered bus load %.0f%%, ' ...
    '%d completion interrupts, DMA CPU demand %.0f us versus ' ...
    'processor-copy demand %.0f us, integrity %d.\n'], ...
    baseline.metrics.beat_service_us, ...
    baseline.metrics.offered_bus_load_pct, ...
    baseline.metrics.completion_interrupt_count, ...
    baseline.cpu.reference_dma_demand_us, ...
    baseline.cpu.processor_copy_demand_us, ...
    baseline.metrics.data_integrity);

%% Sweep 1 - move only completion-block size
blockSizeSweep = [1 2 4 8 16 32];
interruptCount = zeros(size(blockSizeSweep));
dmaCpuDemandUs = zeros(size(blockSizeSweep));
meanReadyLatencyUs = zeros(size(blockSizeSweep));
maxReadyLatencyUs = zeros(size(blockSizeSweep));
for sweepIndex = 1:numel(blockSizeSweep)
    sweptInput = scenarioFcn('baseline', blockSizeSweep(sweepIndex), ...
        0.2, 50, 1, 3, 4);
    swept = runFixture(sweptInput);
    interruptCount(sweepIndex) = ...
        swept.metrics.completion_interrupt_count;
    dmaCpuDemandUs(sweepIndex) = ...
        swept.cpu.reference_dma_demand_us;
    meanReadyLatencyUs(sweepIndex) = ...
        swept.metrics.mean_block_ready_latency_us;
    maxReadyLatencyUs(sweepIndex) = ...
        swept.metrics.max_block_ready_latency_us;
    assert(isequal(swept.input.source_samples, ...
        baseline.input.source_samples) && ...
        swept.input.sample_period_us == ...
        baseline.input.sample_period_us && ...
        swept.input.bytes_per_sample == ...
        baseline.input.bytes_per_sample && ...
        swept.input.bus_rate_bytes_per_us == ...
        baseline.input.bus_rate_bytes_per_us && ...
        swept.input.arbitration_us == baseline.input.arbitration_us && ...
        swept.input.dma_setup_cpu_us == ...
        baseline.input.dma_setup_cpu_us && ...
        swept.input.completion_isr_cpu_us == ...
        baseline.input.completion_isr_cpu_us && ...
        swept.input.processor_copy_cpu_us_per_sample == ...
        baseline.input.processor_copy_cpu_us_per_sample && ...
        swept.input.descriptor_timeout_us == ...
        baseline.input.descriptor_timeout_us && ...
        strcmp(swept.input.timeout_action, ...
        baseline.input.timeout_action) && ...
        strcmp(swept.input.destination_mode, ...
        baseline.input.destination_mode), ...
        'Block-size sweep must isolate only blockSamples.');
    assert(swept.metrics.beat_service_us == ...
        baseline.metrics.beat_service_us && ...
        swept.metrics.reference_bus_busy_us == ...
        baseline.metrics.reference_bus_busy_us && ...
        isequal(swept.timeline.completion_us, ...
        baseline.timeline.completion_us), ...
        'Block grouping must not change beat timing or bus work.');
end
assert(isequal(interruptCount, [32 16 8 4 2 1]) && ...
    isequal(dmaCpuDemandUs, [104 56 32 20 14 11]) && ...
    isequal(meanReadyLatencyUs, [11 36 86 186 386 786]) && ...
    isequal(maxReadyLatencyUs, [11 61 161 361 761 1561]), ...
    'Block-size sweep references changed.');

figure('Name', 'P13 completion-block sweep');
yyaxis left;
plot(blockSizeSweep, dmaCpuDemandUs, 'o-', 'LineWidth', 1.4);
ylabel('DMA setup + ISR CPU demand (us)');
yyaxis right;
plot(blockSizeSweep, maxReadyLatencyUs, 's--', 'LineWidth', 1.4);
ylabel('Maximum block-ready latency (us)');
grid on;
xlabel('Samples per completion block (count)');
title('Lever 1: fewer interrupts trade against later block ownership');
disp(['Mechanism for sweep 1: q and every beat timestamp stay fixed; ' ...
    'only interrupt batching and block-ready ownership change.']);

