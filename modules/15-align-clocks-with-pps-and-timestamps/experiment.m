%% P15 - Align Clocks with PPS and Timestamps
% What inputs, observable effects, and failure modes matter when you align
% Clocks with PPS and Timestamps?
% P14 preserved record identity and order on one synthetic clock. P15 keeps
% those records but gives the timestamping device an independent clock.
modelFcn = @model;
scenarioFcn = @p15_scenario;
runFixture = @(input) modelFcn(input.event_reference_us, ...
    input.pps_sequence_id, input.pps_period_us, ...
    input.clock_offset_us, input.clock_skew_ppm, ...
    input.timestamp_tick_us, input.pps_wait_timeout_us, ...
    input.timeout_action, input.association_mode);

%% Read the affine-clock rule and make one prediction
% A local clock is C(t)=b+(1+s*1e-6)t. A PPS edge supplies a sharp event;
% its sequence ID and timestamp label say which reference second it names.
% Prediction: after removing the first-pulse offset, will a 40-ppm clock
% stay aligned, or will its timestamp error keep growing between pulses?

%% Baseline - identify offset and rate from five PPS anchors
baselineInput = scenarioFcn('baseline');
baseline = runFixture(baselineInput);
baselineRepeat = runFixture(baselineInput);
assert(isequaln(baseline, baselineRepeat), ...
    'The deterministic P15 baseline must repeat exactly.');
expectedLocalUs = 252510:500020:3752650;
expectedRawErrorUs = 2510:20:2650;
expectedOffsetOnlyErrorUs = 10:20:150;
assert(isequal(baseline.clock.event_local_timestamp_us, ...
    expectedLocalUs) && ...
    isequal(baseline.clock.raw_error_us, expectedRawErrorUs) && ...
    isequal(baseline.alignment.offset_only_error_us, ...
    expectedOffsetOnlyErrorUs) && ...
    max(abs(baseline.alignment.corrected_error_us)) < 1e-9 && ...
    abs(baseline.alignment.estimated_offset_us - 2500) < 1e-9 && ...
    abs(baseline.alignment.estimated_skew_ppm - 40) < 1e-9, ...
    'Baseline affine-clock reference values changed.');

figure('Name', 'P15 baseline event timestamp errors');
plot(baseline.input.event_reference_us, ...
    baseline.clock.raw_error_us, '-o', 'LineWidth', 1.5);
hold on;
plot(baseline.input.event_reference_us, ...
    baseline.alignment.offset_only_error_us, '-s', 'LineWidth', 1.5);
plot(baseline.input.event_reference_us, ...
    baseline.alignment.corrected_error_us, '-^', 'LineWidth', 1.5);
hold off;
grid on;
xlabel('Reference event time (us)');
ylabel('Timestamp error (us)');
title('Offset-only correction leaves drift; affine PPS correction removes it');
legend('Raw local', 'One-PPS offset only', 'Offset and rate', ...
    'Location', 'best');

figure('Name', 'P15 baseline PPS anchors');
subplot(2, 1, 1);
stem(baseline.input.pps_sequence_id, ...
    baseline.pps.local_timestamp_us - ...
    baseline.pps.true_reference_us, 'filled');
grid on;
xlabel('PPS sequence ID (count)');
ylabel('Local minus reference (us)');
title('Offset plus 40-ppm drift is visible at named PPS epochs');
subplot(2, 1, 2);
stem(baseline.input.pps_sequence_id, ...
    baseline.pps.fit_residual_us, 'filled');
grid on;
xlabel('PPS sequence ID (count)');
ylabel('Affine fit residual (us)');
title('Correctly associated ideal anchors lie on one affine clock');

fprintf(['Baseline: offset=%.0f us, skew=%.0f ppm, raw end=%g us, ' ...
    'offset-only max=%g us, corrected max=%g us.\n'], ...
    baseline.alignment.estimated_offset_us, ...
    baseline.alignment.estimated_skew_ppm, ...
    baseline.metrics.raw_end_error_us, ...
    baseline.metrics.offset_only_maximum_absolute_error_us, ...
    baseline.metrics.corrected_maximum_absolute_error_us);

%% Sweep 1 - change only initial clock offset
offsetSweepUs = [0 1000 2500 5000 10000];
offsetFirstErrorUs = zeros(size(offsetSweepUs));
offsetFinalErrorUs = zeros(size(offsetSweepUs));
offsetEstimateUs = zeros(size(offsetSweepUs));
offsetCorrectedMaxUs = zeros(size(offsetSweepUs));
for sweepIndex = 1:numel(offsetSweepUs)
    sweptInput = baselineInput;
    sweptInput.clock_offset_us = offsetSweepUs(sweepIndex);
    swept = runFixture(sweptInput);
    offsetFirstErrorUs(sweepIndex) = swept.metrics.raw_start_error_us;
    offsetFinalErrorUs(sweepIndex) = swept.metrics.raw_end_error_us;
    offsetEstimateUs(sweepIndex) = swept.alignment.estimated_offset_us;
    offsetCorrectedMaxUs(sweepIndex) = ...
        swept.metrics.corrected_maximum_absolute_error_us;
    assert(swept.input.clock_skew_ppm == ...
        baseline.input.clock_skew_ppm && ...
        swept.input.timestamp_tick_us == ...
        baseline.input.timestamp_tick_us && ...
        isequal(swept.input.pps_sequence_id, ...
        baseline.input.pps_sequence_id), ...
        'Offset sweep must isolate initial clock offset.');
end
assert(isequal(offsetFirstErrorUs, ...
    [10 1010 2510 5010 10010]) && ...
    isequal(offsetFinalErrorUs, ...
    [150 1150 2650 5150 10150]) && ...
    isequal(offsetEstimateUs, offsetSweepUs) && ...
    max(offsetCorrectedMaxUs) < 1e-9, ...
    'Clock-offset sweep reference vectors changed.');

figure('Name', 'P15 clock offset sweep');
plot(offsetSweepUs, offsetFirstErrorUs, '-o', 'LineWidth', 1.5);
hold on;
plot(offsetSweepUs, offsetFinalErrorUs, '-s', 'LineWidth', 1.5);
hold off;
grid on;
xlabel('Initial local-clock offset (us)');
ylabel('Raw timestamp error (us)');
title('Offset translates the error curve without changing its drift slope');
legend('First event', 'Final event', 'Location', 'best');

%% Mechanism for sweep 1
% Offset b moves every local timestamp by the same amount. The first PPS
% anchor observes b, while later anchors are still needed to identify rate.

%% Sweep 2 - reset, then change only oscillator skew
skewSweepPpm = [-80 -40 0 40 80];
skewFourSecondDriftUs = zeros(size(skewSweepPpm));
skewFinalErrorUs = zeros(size(skewSweepPpm));
skewOffsetOnlyMaxUs = zeros(size(skewSweepPpm));
skewEstimatePpm = zeros(size(skewSweepPpm));
skewCorrectedMaxUs = zeros(size(skewSweepPpm));
for sweepIndex = 1:numel(skewSweepPpm)
    sweptInput = baselineInput;
    sweptInput.clock_skew_ppm = skewSweepPpm(sweepIndex);
    swept = runFixture(sweptInput);
    skewFourSecondDriftUs(sweepIndex) = ...
        (swept.pps.local_timestamp_us(end) - ...
        swept.pps.local_timestamp_us(1)) - 4e6;
    skewFinalErrorUs(sweepIndex) = swept.metrics.raw_end_error_us;
    skewOffsetOnlyMaxUs(sweepIndex) = ...
        swept.metrics.offset_only_maximum_absolute_error_us;
    skewEstimatePpm(sweepIndex) = swept.alignment.estimated_skew_ppm;
    skewCorrectedMaxUs(sweepIndex) = ...
        swept.metrics.corrected_maximum_absolute_error_us;
    assert(swept.input.clock_offset_us == ...
        baseline.input.clock_offset_us && ...
        swept.input.timestamp_tick_us == ...
        baseline.input.timestamp_tick_us && ...
        isequal(swept.input.pps_sequence_id, ...
        baseline.input.pps_sequence_id), ...
        'Skew sweep must reset and isolate oscillator rate error.');
end
assert(isequal(skewFourSecondDriftUs, [-320 -160 0 160 320]) && ...
    isequal(skewFinalErrorUs, [2200 2350 2500 2650 2800]) && ...
    isequal(skewOffsetOnlyMaxUs, [300 150 0 150 300]) && ...
    max(abs(skewEstimatePpm - skewSweepPpm)) < 1e-9 && ...
    max(skewCorrectedMaxUs) < 1e-9, ...
    'Oscillator-skew sweep reference vectors changed.');

figure('Name', 'P15 oscillator skew sweep');
yyaxis left;
plot(skewSweepPpm, skewFourSecondDriftUs, '-o', 'LineWidth', 1.5);
ylabel('Four-second PPS drift (us)');
yyaxis right;
plot(skewSweepPpm, skewOffsetOnlyMaxUs, '-s', 'LineWidth', 1.5);
ylabel('Offset-only maximum error (us)');
grid on;
xlabel('Local oscillator skew (ppm)');
title('Skew accumulates with elapsed time after one offset correction');
legend('PPS drift', 'Offset-only event error', 'Location', 'best');

%% Mechanism for sweep 2
% Skew changes slope: drift = skew_ppm*duration_us/1e6. Two correctly
% associated PPS anchors identify that slope; one edge cannot.

%% Broken case - received position masquerades as PPS identity
correctMissing = runFixture(scenarioFcn('missing-id-correct'));
broken = runFixture(scenarioFcn('broken-arrival-index'));
expectedBrokenErrorUs = ...
    [-62500 -187500 -312500 -437500 -562500 -687500 -812500 -937500];
expectedBrokenResidualUs = ...
    [0 666693.333333333 333346.666666667 0];
assert(correctMissing.metrics.missing_pps_count == 1 && ...
    correctMissing.metrics.association_consistent_with_sequence_identity && ...
    max(abs(correctMissing.alignment.corrected_error_us)) < 1e-9 && ...
    broken.metrics.missing_pps_count == 1 && ...
    ~broken.metrics.association_consistent_with_sequence_identity && ...
    abs(broken.alignment.estimated_skew_ppm - ...
    333386.666666667) < 1e-6 && ...
    max(abs(broken.alignment.corrected_error_us - ...
    expectedBrokenErrorUs)) < 1e-6 && ...
    max(abs(broken.pps.fit_residual_us - ...
    expectedBrokenResidualUs)) < 1e-6, ...
    'Missing-PPS association symptom changed.');

figure('Name', 'P15 deliberately broken PPS association');
plot(broken.input.event_reference_us, ...
    correctMissing.alignment.corrected_error_us, '-o', 'LineWidth', 1.5);
hold on;
plot(broken.input.event_reference_us, ...
    broken.alignment.corrected_error_us, '-s', 'LineWidth', 1.5);
hold off;
grid on;
xlabel('Reference event time (us)');
ylabel('Aligned timestamp error (us)');
title('Broken assumption: arrival position still names the PPS second');
legend('Sequence-ID association', 'Arrival-index association', ...
    'Location', 'best');

%% PPS timeout equality, continuation, cancellation, rollback, recovery
equalityInput = scenarioFcn('missing-id-correct');
equalityInput.pps_wait_timeout_us = 2e6;
equalityInput.timeout_action = 'cancel-alignment';
equality = runFixture(equalityInput);
continued = runFixture(scenarioFcn('timeout-continue'));
cancelled = runFixture(scenarioFcn('timeout-cancel'));
assert(~equality.observation.wait_timed_out && ...
    ~equality.observation.alignment_cancelled && ...
    equality.alignment.available && ...
    continued.observation.wait_timed_out && ...
    ~continued.observation.alignment_cancelled && ...
    continued.alignment.available && ...
    max(abs(continued.alignment.corrected_error_us)) < 1e-9 && ...
    cancelled.observation.wait_timed_out && ...
    cancelled.observation.alignment_cancelled && ...
    cancelled.observation.retained_pps_count == 1 && ...
    cancelled.observation.censored_pps_count == 3 && ...
    ~cancelled.alignment.available && ...
    all(isnan(cancelled.alignment.corrected_error_us)), ...
    'PPS timeout equality, continuation, or cancellation changed.');

rollback = runFixture(baselineInput);
recovered = runFixture(scenarioFcn('baseline'));
assert(isequaln(rollback, baseline) && isequaln(recovered, baseline), ...
    'Clean pure-model input must provide exact computational recovery.');

figure('Name', 'P15 timeout and cancellation boundary');
bar([continued.observation.retained_pps_count, ...
    cancelled.observation.retained_pps_count; ...
    continued.observation.censored_pps_count, ...
    cancelled.observation.censored_pps_count]');
grid on;
xlabel('Timeout action (case)');
ylabel('PPS captures (count)');
xticklabels({'continue waiting', 'cancel alignment'});
legend('Retained', 'Censored', 'Location', 'best');
title('Cancellation censors future anchors; it does not change raw timestamps');

disp(['A PPS edge supplies precise phase, while its sequence identity and ' ...
    'trusted timestamp label supply epoch.']);
disp(['Canceling acquisition leaves the raw local timestamps unchanged; ' ...
    'a clean stateless rerun is computational recovery, not rollback of ' ...
    'a receiver or clock.']);
disp(['These deterministic simulated references are not MATLAB-runtime, ' ...
    'rendered-UI, PPS/GNSS hardware, oscillator, bench, HIL, field, ' ...
    'RT1/RT2, Unreal, signing, deployment, or production validation.']);

