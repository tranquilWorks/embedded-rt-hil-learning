disp(['Checks are deterministic calculations, not MATLAB-runtime, ' ...
    'rendered-UI, PPS/GNSS hardware, oscillator, bench, HIL, field, ' ...
    'or production evidence unless executed and retained on named systems.']);
disp('P15 checks passed.');
end

function assertReject(callable, expectedIdentifier)
didReject = false;
receivedIdentifier = '<none>';
try
    callable();
catch caught
    receivedIdentifier = caught.identifier;
    didReject = strcmp(caught.identifier, expectedIdentifier);
end
assert(didReject, 'Expected rejection %s but received %s.', ...
    expectedIdentifier, receivedIdentifier);
end
