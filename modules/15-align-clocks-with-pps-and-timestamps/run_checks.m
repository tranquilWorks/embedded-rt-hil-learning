rmpath(moduleFolder);
addpath(p01Folder, '-begin');
clear model;
callbackInput = callbackScenario('baseline');
callbackOut = callbackModel(callbackInput.event_reference_us, ...
    callbackInput.pps_sequence_id, callbackInput.pps_period_us, ...
    callbackInput.clock_offset_us, callbackInput.clock_skew_ppm, ...
    callbackInput.timestamp_tick_us, ...
    callbackInput.pps_wait_timeout_us, callbackInput.timeout_action, ...
    callbackInput.association_mode);
assert(isequaln(callbackOut, clean), ...
    ['Callback-bound P15 dependencies must survive module path cleanup ' ...
    'and a conflicting generic model path.']);
clear searchPathCleanup;

%% Malformed input and resource-bound rejection
