%% Wait timeout, cancellation, unlock ownership, and recovery
continuesInput = p10_scenario('wait-continue');
continues = runFixture(continuesInput);
assert(continues.tasks.wait_timed_out(3) && ...
    continues.tasks.wait_timeout_time_ms(3) == 4 && ...
    ~continues.tasks.cancelled_while_waiting(3) && ...
    continues.tasks.completion_ms(3) == 7 && ...
    isequal(continues.timeline.cpu_owner_task_id, expectedOwner), ...
    'Continue-waiting must record one timeout without withdrawing donation.');

exactTimeoutInput = input;
exactTimeoutInput.wait_timeout_ms(3) = 3;
exactTimeoutInput.timeout_action = 'cancel-waiter';
exactHandoff = runFixture(exactTimeoutInput);
assert(~exactHandoff.tasks.wait_timed_out(3) && ...
    ~exactHandoff.tasks.cancelled_while_waiting(3) && ...
    exactHandoff.tasks.resource_acquire_ms(3) == 5, ...
    'Mutex availability at the timeout boundary must win before timeout.');

cancelInput = p10_scenario('wait-cancel');
cancelledWait = runFixture(cancelInput);
expectedCancelledOwner = [1 2 1 1 2 2 2 2 1 1 1 0 0 0 0 0];
assert(isequal(cancelledWait.timeline.cpu_owner_task_id, ...
    expectedCancelledOwner) && ...
    cancelledWait.tasks.wait_timed_out(3) && ...
    cancelledWait.tasks.cancellation_time_ms(3) == 4 && ...
    cancelledWait.tasks.cancelled_work_ms(3) == 2 && ...
    isnan(cancelledWait.tasks.completion_ms(3)), ...
    'Cancel-waiter must remove High at 4 ms without inventing completion.');
assert(cancelledWait.tasks.resource_release_ms(1) == 9 && ...
    cancelledWait.tasks.boost_time_ms(1) == 2 && ...
    cancelledWait.metrics.served_work_ms == 11 && ...
    cancelledWait.metrics.cancelled_work_ms == 2 && ...
    cancelledWait.metrics.remaining_work_ms == 0 && ...
    cancelledWait.metrics.work_conservation_error_ms == 0, ...
    ['Cancelling a waiter must withdraw donation but must not unlock the ' ...
    'Low-owned mutex or lose work accounting.']);
rollback = runFixture(input);
assert(isequaln(rollback, baseline), ...
    'A clean call after waiter cancellation must recover exact baseline state.');

disp(['Wait cancellation here removes modeled pending work; it is not an ' ...
    'asynchronous RTOS task-delete API, mutex cleanup proof, or physical rollback.']);
disp(['Priority-inversion outputs are synthetic calculations, not proof of ' ...
